#!/usr/bin/env python3
"""Write tests/wl_wire_real/vectors.h from pc/wifi_session.

    PYTHONDONTWRITEBYTECODE=1 python3 tools/gen_wire_vectors.py

tests/wl_hs and tests/wl_frame run the board's handshake and frame code on a
toy cipher, so they cannot say whether the bytes are the PC's. This holds
wl_hs.c and wl_frame.c, on the real cipher, to pc/wifi_session.py: one
handshake (M1, M2, M3, both session keys), one discovery query and answer,
and sealed frames of each type in both directions, every one produced by the
Python. The board's Nb is the 0x5a fill that the host test's sys_csrand_get
stub returns, so M1 is known in advance.

Deterministic, standard library only, and nothing here is a secret: the key
protects nothing. tests/test_vectors_are_generated.py fails when the
committed header and this script disagree, so change this and run it, never
the output.
"""
from __future__ import annotations

import hashlib
import hmac
import os
import struct
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "tests", "wl_wire_real", "vectors.h")

KEY = bytes(range(0x40, 0x60))
NB = b"\x5a" * 16                 # what the host test's RNG stub returns
NP = bytes(range(0xb0, 0xc0))
NQ = bytes(range(0xa0, 0xb0))
PORT = 49731
# (type, body): body is what follows the type byte on the wire.
FRAMES = (
    (b"L", b'{"t":"usage","p":"c","s":42}\n'),
    (b"O", struct.pack(">I", 0) + bytes(range(256)) * 2),
    (b"G", struct.pack(">I", 7) + b"abc"),
    (b"L", b"x" * 511 + b"\n"),                  # 512: the widest line
    (b"O", struct.pack(">I", 1 << 31) + b"y" * 512),  # 517: the widest frame
)


def _arr(name: str, b: bytes) -> str:
    rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 12])
            for i in range(0, len(b), 12)]
    return (f"static const uint8_t {name}[{len(b)}] = {{\n\t"
            + ",\n\t".join(rows) + ",\n};\n")


def source() -> str:
    sys.path.insert(0, ROOT)
    from pc import wifi_crypto as wc
    from pc import wifi_session as ws

    # M2 and the keys come out of the PC's own client_handshake, driven by a
    # scripted socket; M3 is computed here with hmac directly, so the client
    # accepting it proves the PC's argument order, not this script's copy.
    m1 = ws.M1_MAGIC + NB
    m3 = hmac.new(KEY, b"blink-wifi-1 board" + NB + NP,
                  hashlib.sha256).digest()

    class Script:
        def __init__(self):
            self.rx, self.sent = m1 + m3, b""

        def settimeout(self, _):
            pass

        def recv(self, n):
            out, self.rx = self.rx[:n], self.rx[n:]
            return out

        def sendall(self, data):
            self.sent += data

    def fixed(n, value):
        return lambda _n: value

    real = os.urandom
    sock = Script()
    try:
        os.urandom = fixed(16, NP)
        sess = ws.client_handshake(sock, KEY)
        os.urandom = fixed(16, NQ)
        nq, q = ws.disc_query(KEY)
    finally:
        os.urandom = real
    assert nq == NQ
    m2, k_pb, k_bp = sock.sent, sess._ktx, sess._krx
    assert len(m2) == 48 and m2[:16] == NP
    assert k_pb == wc.hkdf_sha256(NB + NP, KEY, b"blink-wifi-1 session",
                                  64)[:32]
    pb = struct.pack(">H", PORT)
    a = ws.A_MAGIC + hmac.new(KEY, b"blink-disc-1 a" + NQ + pb,
                              hashlib.sha256).digest()[:16] + pb
    assert ws.disc_answer_port(KEY, NQ, a) == PORT

    pc_tx = ws.Session(k_pb, k_bp)      # PC -> board
    pc_rx = ws.Session(k_bp, k_pb)      # the same keys, to seal board -> PC
    to_board, to_pc = [], []
    for typ, body in FRAMES:
        for sess, dest in ((pc_tx, to_board), (pc_rx, to_pc)):
            dest.append(sess._seal(typ, body))
    # The Python opens its own frames: the generator would be worthless if
    # it wrote bytes the PC itself refuses.
    check = ws.Session(k_pb, k_bp)
    got = check.feed(b"".join(to_pc))
    assert got == [(t.decode(), b) for t, b in FRAMES]

    o = [
        "/* GENERATED by tools/gen_wire_vectors.py from pc/wifi_session.py.",
        " * Do not edit: change the generator and run it;",
        " * tests/test_vectors_are_generated.py fails on any difference. */",
        "#ifndef WL_WIRE_VECTORS_H",
        "#define WL_WIRE_VECTORS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define WLW_PORT {PORT}",
        f"#define WLW_NFRAMES {len(FRAMES)}",
        "",
    ]
    for name, b in (("wlw_key", KEY), ("wlw_np", NP), ("wlw_m1", m1),
                    ("wlw_m2", m2), ("wlw_m3", m3), ("wlw_k_pb", k_pb),
                    ("wlw_k_bp", k_bp), ("wlw_q", q), ("wlw_a", a)):
        o.append(_arr(name, b))
    o += ["struct wlw_frame {", "\tchar type;", "\tuint16_t body_len;",
          "\tuint16_t frame_len;", "\tconst uint8_t *body;",
          "\tconst uint8_t *to_board;   /* sealed under k_pb, counter = index */",
          "\tconst uint8_t *to_pc;      /* sealed under k_bp, counter = index */",
          "};", ""]
    for i, (typ, body) in enumerate(FRAMES):
        o.append(_arr(f"wlw_body{i}", body))
        o.append(_arr(f"wlw_tb{i}", to_board[i]))
        o.append(_arr(f"wlw_tp{i}", to_pc[i]))
    o.append("static const struct wlw_frame wlw_frames[WLW_NFRAMES] = {")
    for i, (typ, body) in enumerate(FRAMES):
        o.append(f"\t{{ '{typ.decode()}', {len(body)}, {len(to_board[i])}, "
                 f"wlw_body{i}, wlw_tb{i}, wlw_tp{i} }},")
    o += ["};", "", "#endif /* WL_WIRE_VECTORS_H */", ""]
    return "\n".join(o)


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(source())
    print("wrote", os.path.relpath(OUT, ROOT))
