#!/usr/bin/env python3
"""Write tests/wl_crypto_real/vectors.h from pc/wifi_crypto.

    PYTHONDONTWRITEBYTECODE=1 python3 tools/gen_aead_vectors.py

The WiFi link has two implementations of one cipher: the daemon's pure-Python
ChaCha20-Poly1305 (pc/wifi_crypto.py) and the board's mbedTLS behind
firmware/src/wl_crypto.h. Each passes the RFC's vectors on its own, and the
RFC's vectors stop at 114 bytes. A frame is anything from 1 to 517 bytes
(WL_PT_MAX, spec S6.3), and the board emits no variable-length line the PC
could sweep on hardware (S7.4), so the lengths in between are proved here:
this script seals with the Python, the host test
(tests/wl_crypto_real/host_test.c) seals the same inputs with mbedTLS and
requires the same bytes, opens every one, and refuses every corrupted one.

What the header holds, per counter in 0, 1, 2^32, 2^64-2 (the counter's two
32-bit halves each carry, and the last counter a session may use):

- one key and one 517-byte plaintext pool;
- the ciphertext of the whole pool. ChaCha20 is a stream, so the ciphertext
  of pool[0:n] is exactly the first n bytes of it under the same key and
  nonce, and every length 0..517 is checked against that prefix, byte for
  byte. Storing 2072 ciphertexts separately would have been a 2 MB header
  saying the same thing;
- one tag per length, which is where the lengths differ: the tag covers the
  AAD (the frame's two length bytes) and the ciphertext length.

The nonce and AAD are not stored: they are the wire's, four zero bytes then
the big-endian counter, and the two big-endian length bytes (S6.3), and the
host test builds them the way wl_frame.c will.

Then 60 corrupted cases, 20 at each of the lengths 1, 64 and 517: one bit
flipped in the ciphertext, the AAD or the tag, at a position drawn from the
seed. And a few HMAC and HKDF results in the handshake's own shapes (S6.2).

Deterministic: a fixed seed and the standard library's Random, so the same
pc/wifi_crypto always gives the same bytes. tests/test_vectors_are_generated.py
fails when the committed header and this script disagree, so change this and
run it, never the output. Nothing here is a secret; the keys are drawn from
the seed and protect nothing.
"""
from __future__ import annotations

import hashlib
import hmac
import os
import random
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "tests", "wl_crypto_real", "vectors.h")

SEED = 0xB11C2026
PT_MAX = 517                     # WL_PT_MAX, spec S6.3
COUNTERS = (0, 1, 1 << 32, (1 << 64) - 2)
BAD_LENGTHS = (1, 64, 517)
BAD_PER_LENGTH = 20
BAD_FIELDS = ("WLV_BAD_CT", "WLV_BAD_AAD", "WLV_BAD_TAG")


def nonce(counter: int) -> bytes:
    return b"\x00" * 4 + counter.to_bytes(8, "big")


def aad(n: int) -> bytes:
    return n.to_bytes(2, "big")


def _hex(b: bytes, indent: str = "\t") -> str:
    """A C initialiser body, 12 bytes a line."""
    rows = []
    for i in range(0, len(b), 12):
        rows.append(indent + ", ".join(f"0x{x:02x}" for x in b[i:i + 12])
                    + ",")
    return "\n".join(rows)


def source() -> str:
    from pc import wifi_crypto as wc

    rnd = random.Random(SEED)

    def draw(n):
        return bytes(rnd.getrandbits(8) for _ in range(n))

    out = [
        "/* GENERATED by tools/gen_aead_vectors.py from pc/wifi_crypto.py.",
        " * Do not edit: change the generator and run it;",
        " * tests/test_vectors_are_generated.py fails on any difference. */",
        "#ifndef WL_VECTORS_H",
        "#define WL_VECTORS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define WLV_PT_MAX {PT_MAX}",
        f"#define WLV_NCTR {len(COUNTERS)}",
        "",
        "struct wlv_ctr {",
        "\tuint64_t counter;",
        "\tuint8_t key[32];",
        "\tuint8_t pt[WLV_PT_MAX];",
        "\tuint8_t ct[WLV_PT_MAX];         /* seal of the whole pool */",
        "\tuint8_t tag[WLV_PT_MAX + 1][16]; /* seal of pt[0:n], for each n */",
        "};",
        "",
        "static const struct wlv_ctr wlv_ctr[WLV_NCTR] = {",
    ]
    for c in COUNTERS:
        key, pt = draw(32), draw(PT_MAX)
        ct, _ = wc.aead_seal(key, nonce(c), aad(PT_MAX), pt)
        out += ["{", f"\t.counter = 0x{c:016x}ULL,", "\t.key = {",
                _hex(key, "\t\t"), "\t},", "\t.pt = {", _hex(pt, "\t\t"),
                "\t},", "\t.ct = {", _hex(ct, "\t\t"), "\t},", "\t.tag = {"]
        for n in range(PT_MAX + 1):
            ct_n, tag = wc.aead_seal(key, nonce(c), aad(n), pt[:n])
            assert ct_n == ct[:n]       # the prefix property the test leans on
            out.append("\t\t{ " + ", ".join(f"0x{x:02x}" for x in tag)
                       + " },")
        out += ["\t},", "},"]
    out += ["};", ""]

    # Corrupted cases: index into wlv_ctr, the length, the field, which byte
    # of it and which bit. The AAD is two bytes, the tag 16, the ciphertext n.
    out += [
        "enum { WLV_BAD_CT, WLV_BAD_AAD, WLV_BAD_TAG };",
        "",
        "struct wlv_bad { uint8_t ctr; uint16_t n; uint8_t field;"
        " uint16_t byte; uint8_t bit; };",
        "",
        f"#define WLV_NBAD {len(BAD_LENGTHS) * BAD_PER_LENGTH}",
        "static const struct wlv_bad wlv_bad[WLV_NBAD] = {",
    ]
    for n in BAD_LENGTHS:
        for i in range(BAD_PER_LENGTH):
            field = i % 3
            size = (n, 2, 16)[field]
            out.append(f"\t{{ {rnd.randrange(len(COUNTERS))}, {n}, "
                       f"{BAD_FIELDS[field]}, {rnd.randrange(size)}, "
                       f"{rnd.randrange(8)} }},")
    out += ["};", ""]

    # HMAC and HKDF in the handshake's shapes: a 32-byte key over the M2
    # and M3 inputs ("blink-wifi-1 pc" || Nb || Np is 47 bytes,
    # "blink-wifi-1 board" || Nb || Np 50), and the session derivation
    # (salt Nb || Np, ikm K, info "blink-wifi-1 session", L 64).
    out += [
        "struct wlv_hmac { uint8_t key[32]; uint8_t n; uint8_t msg[64];"
        " uint8_t mac[32]; };",
        "",
        "#define WLV_NHMAC 4",
        "static const struct wlv_hmac wlv_hmac[WLV_NHMAC] = {",
    ]
    for label in (b"blink-wifi-1 pc", b"blink-wifi-1 board",
                  b"blink-disc-1 q", b"blink-disc-1 a"):
        key = draw(32)
        msg = label + draw(32 if label.startswith(b"blink-wifi") else 16)
        mac = hmac.new(key, msg, hashlib.sha256).digest()
        out += ["\t{", "\t\t.key = {", _hex(key, "\t\t\t"), "\t\t},",
                f"\t\t.n = {len(msg)},", "\t\t.msg = {", _hex(msg, "\t\t\t"),
                "\t\t},", "\t\t.mac = {", _hex(mac, "\t\t\t"), "\t\t},",
                "\t},"]
    out += ["};", ""]

    info = b"blink-wifi-1 session"
    out += [
        "struct wlv_hkdf { uint8_t salt[32]; uint8_t ikm[32];"
        " uint8_t okm[64]; };",
        "",
        "static const char wlv_hkdf_info[] = \"blink-wifi-1 session\";",
        "#define WLV_NHKDF 3",
        "static const struct wlv_hkdf wlv_hkdf[WLV_NHKDF] = {",
    ]
    for _ in range(3):
        salt, ikm = draw(32), draw(32)
        okm = wc.hkdf_sha256(salt, ikm, info, 64)
        out += ["\t{", "\t\t.salt = {", _hex(salt, "\t\t\t"), "\t\t},",
                "\t\t.ikm = {", _hex(ikm, "\t\t\t"), "\t\t},",
                "\t\t.okm = {", _hex(okm, "\t\t\t"), "\t\t},", "\t},"]
    out += ["};", "", "#endif /* WL_VECTORS_H */", ""]
    return "\n".join(out)


def main() -> int:
    sys.path.insert(0, ROOT)
    text = source()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
