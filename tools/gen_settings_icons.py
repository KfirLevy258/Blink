#!/usr/bin/env python3
"""Draw the four Settings tile icons and write them out as LVGL A8 images.

    PYTHONDONTWRITEBYTECODE=1 python3 tools/gen_settings_icons.py

writes firmware/src/settings_icons.c and settings_icons.h. Standard library
only, and deterministic: the same script always writes the same bytes, so the
generated file can be checked against it rather than trusted.

Why drawn here and not taken from an icon set: every pixel in this repo's
firmware has to be something we can say where it came from. A captured or
downloaded bitmap is neither reproducible nor ours, and the house rule for
fixtures (generated by committed code, never captured) applies to art for the
same reason. Each icon is a handful of shapes in a signed-distance function,
sampled 4 x 4 per pixel for the antialiasing.

Why A8: an alpha-only image carries no colour of its own. LVGL's software
renderer blends an A8 image as a mask filled with the object's
image_recolor colour (lv_draw_sw_img.c), so the tiles set that to the
theme's text colour and the icons follow all twelve themes and a custom one,
light grounds included, with nothing stored per theme. 28 x 28 x 1 byte is
784 B an icon, 3136 B for the four; the whole Settings redesign measured
+3.2 KB on the ESP32 image.

Colour emoji were the other way to get pictures on the tiles, and are not
one: LVGL draws no colour font, so each would be a 28 x 28 RGB565A8 image
(2352 B), in fixed colours that no theme could change.

tests/test_settings_icons.py fails if the committed files and this script
disagree, so change the drawing here and run it, never the output.
"""
import math
import os

SIZE = 28
SS = 4          # supersamples per axis
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                   "firmware", "src")


def seg(px, py, ax, ay, bx, by):
    """Distance from (px, py) to the segment a-b."""
    dx, dy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) /
                     (dx * dx + dy * dy or 1.0)))
    return math.hypot(px - ax - t * dx, py - ay - t * dy)


C = SIZE / 2.0
STROKE = 1.25   # half the line width: 2.5 px lines


# The eight compass directions, from sqrt alone. math.sqrt is IEEE
# correctly rounded on every platform, and CPython computes math.hypot
# itself rather than asking the platform, so both give the same bits
# everywhere in practice; cos and sin come from the platform's libm, which
# may differ in the last place, and a sample sitting on an edge could then
# land the other way on Windows and fail the check against the committed
# file. What actually rules that out is margin: tests/test_settings_icons.py
# checks that no sample lies within 1e-9 of an edge (the nearest is 1.3e-3),
# and CI runs it on Windows and on Python 3.9 as well.
_R = math.sqrt(0.5)
RAYS = ((1, 0), (_R, _R), (0, 1), (-_R, _R), (-1, 0), (-_R, -_R), (0, -1),
        (_R, -_R))


def sun(x, y):
    """Brightness: a disc and eight rays."""
    d = math.hypot(x - C, y - C) - 5.0
    for ca, sa in RAYS:
        d = min(d, seg(x, y, C + 8.0 * ca, C + 8.0 * sa,
                       C + 11.0 * ca, C + 11.0 * sa) - STROKE)
    return d


def contrast(x, y):
    """Theme: a ring with its left half filled -- the usual appearance
    mark, and it says light-and-dark without naming either."""
    r = math.hypot(x - C, y - C)
    ring = abs(r - 11.0) - STROKE
    half = max(r - 11.0, x - C)
    return min(ring, half)


def focus(x, y):
    """Focus: a viewfinder's four corner brackets around a dot."""
    d = math.hypot(x - C, y - C) - 3.2
    lo, hi, arm = 3.0, SIZE - 3.0, 7.0
    for cx, sx in ((lo, 1), (hi, -1)):
        for cy, sy in ((lo, 1), (hi, -1)):
            d = min(d, seg(x, y, cx, cy, cx + sx * arm, cy) - STROKE,
                    seg(x, y, cx, cy, cx, cy + sy * arm) - STROKE)
    return d


def update(x, y):
    """Update: an arrow down into a tray."""
    d = seg(x, y, C, 3.0, C, 17.0) - STROKE
    d = min(d, seg(x, y, C, 17.5, C - 6.5, 11.0) - STROKE,
            seg(x, y, C, 17.5, C + 6.5, 11.0) - STROKE)
    d = min(d, seg(x, y, 4.0, 18.0, 4.0, 24.0) - STROKE,
            seg(x, y, 4.0, 24.0, SIZE - 4.0, 24.0) - STROKE,
            seg(x, y, SIZE - 4.0, 24.0, SIZE - 4.0, 18.0) - STROKE)
    return d


ICONS = (("bright", sun), ("theme", contrast), ("focus", focus),
         ("update", update))


def render(fn):
    px = []
    for j in range(SIZE):
        for i in range(SIZE):
            hit = 0
            for sj in range(SS):
                for si in range(SS):
                    if fn(i + (si + 0.5) / SS, j + (sj + 0.5) / SS) <= 0:
                        hit += 1
            px.append(round(255 * hit / (SS * SS)))
    return px


def sources():
    """The text of settings_icons.c and settings_icons.h, as a pair."""
    c = ["/* Generated by tools/gen_settings_icons.py -- do not edit. */",
         '#include "settings_icons.h"', ""]
    # Aligned to LV_DRAW_BUF_ALIGN because LVGL checks it on every draw.
    # A plain uint8_t array is placed on any byte, and in 94d07db's image
    # all four landed 2 bytes off (0x3f43872e, ...a3e, ...d4e, ...05e).
    # lv_draw_buf_init() then printed "Data is not aligned, ignored" every
    # time an icon was decoded for drawing, which with no image cache is
    # every draw. That was 836 warnings in one full_touch board run and
    # 207 in a popups run, every one of LVGL's lines in both. The draw was
    # right ("ignored" means it used the pointer as given, and the A8 blend
    # reads bytes), but each warning is a log line the panel has to print.
    # GCC's attribute rather than Zephyr's __aligned so the host harness,
    # which compiles this file without Zephyr's headers, builds it too.
    h = ["/* Generated by tools/gen_settings_icons.py -- do not edit. */",
         "#ifndef SETTINGS_ICONS_H", "#define SETTINGS_ICONS_H",
         "#include <lvgl.h>", ""]
    for name, fn in ICONS:
        px = render(fn)
        c.append(f"static const uint8_t icon_{name}_map[]"
                 " __attribute__((aligned(LV_DRAW_BUF_ALIGN))) = {")
        for k in range(0, len(px), 14):
            c.append("\t" + ", ".join(f"0x{v:02x}" for v in px[k:k + 14])
                     + ",")
        c += ["};", "",
              f"const lv_image_dsc_t settings_icon_{name} = {{",
              "\t.header.magic = LV_IMAGE_HEADER_MAGIC,",
              "\t.header.cf = LV_COLOR_FORMAT_A8,",
              f"\t.header.w = {SIZE},", f"\t.header.h = {SIZE},",
              f"\t.header.stride = {SIZE},",
              f"\t.data_size = sizeof(icon_{name}_map),",
              f"\t.data = icon_{name}_map,", "};", ""]
        h.append(f"extern const lv_image_dsc_t settings_icon_{name};")
    h += ["", "#endif", ""]
    return "\n".join(c), "\n".join(h)


def main():
    c, h = sources()
    for name, text in (("settings_icons.c", c), ("settings_icons.h", h)):
        with open(os.path.join(OUT, name), "w", encoding="utf-8",
                  newline="\n") as f:
            f.write(text)


if __name__ == "__main__":
    main()
