#!/bin/sh
# Watch the OpenCode contract where it is defined.
#
#   tests/ci/check_opencode_contract.sh [git-ref]      default: dev
#
# OpenCode support rests on two things OpenCode never promised us:
#
#   * tools/blink-opencode.js, a plugin OpenCode loads from
#     <config>/opencode/plugin/, which turns bus events (session.status,
#     permission.asked, question.replied, ...) into the hook slot files
#     claude_state already reads;
#   * pc/providers/opencode.py, which finds the GLM Coding Plan key in
#     <data>/opencode/auth.json (or, from 2.0, the credential table in
#     opencode.db) and the activity clock in opencode.db and its WAL, and
#     asks z.ai's quota endpoint for the two windows.
#
# Every one of those names is a string literal in OpenCode's TypeScript, and
# OpenCode is open source, so the contract can be checked at the ref that
# ships, without installing it and without an account. That is the whole idea
# of tests/ci/check_codex_contract.sh, and this is the same script for the
# third provider. docs/research/opencode-contract.md has the measurements
# behind each check; docs/plans/opencode.md has the design they serve.
#
# Unlike the Codex check, this one does NOT stop at the first failure. It
# reports every broken assumption and then fails. The reason is the `dev`
# branch: in October 2026 it is the OpenCode 2.0 rewrite, which moves most of
# the files below, and the point of running it is to learn the whole list of
# what 2.0 breaks in one run -- not one line per push, rediscovered over a
# week. On a release tag the list should be empty.
#
# WHAT THIS CANNOT DO:
#   * Prove the plugin loads and the events fire. That is
#     tests/ci/check_opencode_plugin.sh, which runs the plugin under node.
#   * Check the z.ai quota endpoint's response. It answers only to a real
#     Coding Plan key, and CI has none (and must not: a key in CI is a key in
#     a public repo's logs the first time something echoes it). Without a key
#     every request gets the same HTTP 200 {"success":false,"code":1001}, which
#     says nothing about the shape of a real answer. The parser is pinned
#     instead by fixtures GENERATED by tests/support/opencode_fixture.py -- in
#     the CREDIT_LIMIT / TOKENS_LIMIT shapes published in CodexBar's issues
#     #2522 and #2724 and parsed by CodexBar's zai.js -- never by a captured
#     reply, which would carry somebody's plan into a public repo.
#     As an early warning, section 9 below reads CodexBar's zai.js: CodexBar
#     polls that endpoint for thousands of people, so a change in the unit
#     codes or the success envelope tends to show up there first.
#
# OPENCODE_SRC_DIR=<dir> reads the files from a checkout of OpenCode at the
# ref instead of fetching them (paths are relative to the repo root, as in
# `git clone --branch v1.19.3 https://github.com/anomalyco/opencode`), for
# running this where curl is not available. The third-party sections need the
# network and are skipped in that mode.
#
# OPENCODE_THIRD_PARTY=warn|fail|skip, default warn: what a mismatch in
# models.dev or CodexBar does. Those repos are not OpenCode and are not
# versioned with it, so on the blocking release cell a refactor there must not
# block a merge here -- that is the lesson of 6000c9b, where the Codex check
# read an upstream refactor as a broken contract. The experimental cell sets
# `fail`, which turns the same mismatch red where somebody will look.
set -eu

# shellcheck source=tests/ci/lib.sh
. "$(dirname -- "$0")/lib.sh"

# dev, not main: OpenCode's default branch is `dev`, and `main` does not
# track it. Releases are tags vX.Y.Z; the workflow resolves the latest.
REF="${1:-dev}"
ci_label "opencode $REF"
RAW="https://raw.githubusercontent.com/anomalyco/opencode/$REF"
WORK="${TMPDIR:-/tmp}/blink-opencode-contract"
THIRD_PARTY="${OPENCODE_THIRD_PARTY:-warn}"
[ -n "${OPENCODE_SRC_DIR:-}" ] && THIRD_PARTY=skip
mkdir -p "$WORK"

MISSES=0
WARNS=0
GROUP=0
# miss <what> -- one broken assumption. Same format as lib.sh's fail(), so
# a CI log reads the same, but it does not exit.
miss() {
	printf 'FAIL [%s] %s\n' "$CI_LABEL" "$*" >&2
	MISSES=$((MISSES + 1))
}

# group, then pass <summary>: the summary line prints only if nothing in the
# group missed or warned. An "ok" under a FAIL for the same file reads as a
# contradiction in a log somebody is skimming at a red X.
group() { GROUP=$((MISSES + WARNS)); }
pass() {
	if [ $((MISSES + WARNS)) -eq "$GROUP" ]; then ok "$*"; fi
}

# fetch <repo path> -> prints the local file holding it, or nothing if the
# ref does not have it. A missing file is itself the finding (2.0 moves
# whole packages), so the caller reports it under its own name.
fetch() {
	if [ -n "${OPENCODE_SRC_DIR:-}" ]; then
		[ -s "$OPENCODE_SRC_DIR/$1" ] && printf '%s' "$OPENCODE_SRC_DIR/$1"
		return 0
	fi
	out="$WORK/$(printf '%s' "$1" | tr '/' '_')"
	rm -f "$out"
	curl -fsSL "$RAW/$1" -o "$out" 2>/dev/null || return 0
	[ -s "$out" ] && printf '%s' "$out"
	return 0
}

# has <file> <fixed string> -- grep -F, false for a file that was not fetched.
has() { [ -n "$1" ] && grep -qF -- "$2" "$1"; }

# need <file> <repo path> -- report a missing file once, return whether to go on.
need() {
	group
	[ -n "$1" ] && return 0
	miss "$2 is gone at $REF -- the checks that read it cannot run; find where it moved"
	return 1
}

printf '== OpenCode at %s\n' "$REF"

# 1. Where everything lives. pc/providers/opencode.py and the installer both
#    compute <data>/opencode and <config>/opencode the way xdg-basedir does:
#    $XDG_DATA_HOME else ~/.local/share, $XDG_CONFIG_HOME else ~/.config --
#    on macOS too (not ~/Library) and on Windows too (not %APPDATA%), because
#    xdg-basedir has no platform branch. The v1.2.0 release note says
#    "%APPDATA% on windows"; the code says otherwise, and the code wins.
P=packages/core/src/global.ts
F=$(fetch $P)
if need "$F" $P; then
	has "$F" 'from "xdg-basedir"' || miss "global.ts no longer takes its roots from xdg-basedir -- re-derive every path"
	has "$F" 'const app = "opencode"' || miss "the app directory is no longer 'opencode'"
	has "$F" 'const data = path.join(xdgData!, app)' || miss "the data dir is no longer xdgData/opencode -- opencode.db and auth.json moved"
	has "$F" 'const config = path.join(xdgConfig!, app)' || miss "the config dir is no longer xdgConfig/opencode -- the plugin is installed in the wrong place"
	pass "data and config dirs are still xdg-basedir's, under 'opencode'"
fi

# 1b. ...and xdg-basedir itself still has no Windows case. The claim is about
#     one version of somebody else's package, so read that version. A major
#     bump, or a platform branch appearing, means Windows paths need
#     measuring again on a Windows box.
P=packages/core/package.json
F=$(fetch $P)
if need "$F" $P; then
	xdg=$(sed -n 's/^[[:space:]]*"xdg-basedir": "[^0-9]*\([0-9][0-9.]*\)".*/\1/p' "$F" | head -n 1)
	if [ -z "$xdg" ]; then
		miss "core no longer depends on xdg-basedir -- see check 1"
	elif [ -n "${OPENCODE_SRC_DIR:-}" ]; then
		ok "xdg-basedir $xdg (its source is not checked offline)"
	else
		XDG="$WORK/xdg-basedir-$xdg.js"
		if ! curl -fsSL "https://unpkg.com/xdg-basedir@$xdg/index.js" -o "$XDG" 2>/dev/null; then
			miss "could not fetch xdg-basedir@$xdg to check it for a Windows case"
		elif grep -q 'win32\|process\.platform\|APPDATA' "$XDG"; then
			miss "xdg-basedir@$xdg has a platform branch -- Windows paths are no longer ~/.local/share"
		elif ! grep -qF "path.join(homeDirectory, '.local', 'share')" "$XDG"; then
			miss "xdg-basedir@$xdg no longer defaults data to ~/.local/share"
		else
			ok "xdg-basedir $xdg still has no Windows case"
		fi
	fi
fi

# 2. The database. The reader uses opencode.db only for an activity clock --
#    the mtime of the file and of its WAL -- so what matters is the name and
#    that it is WAL: in the lab almost all of 836 KB of writes sat in
#    opencode.db-wal while opencode.db stayed at 4 KB, so an mtime check on
#    the .db alone saw nothing happen. Release channels (latest/beta/prod)
#    write opencode.db; anything else writes opencode-<channel>.db.
P=packages/core/src/database/database.ts
F=$(fetch $P)
if need "$F" $P; then
	has "$F" 'PRAGMA journal_mode = WAL' || miss "the DB is no longer WAL -- the -wal mtime is no longer where activity shows"
	has "$F" 'return join(Global.Path.data, "opencode.db")' || miss "released builds no longer write <data>/opencode.db"
	grep -q '\["latest",' "$F" || miss "the release channel list changed -- re-read which builds write opencode.db"
	pass "the DB is <data>/opencode.db, in WAL mode"
fi

# 3. Plugin discovery. Install writes <config>/opencode/plugin/blink.js; that
#    works because every config dir is scanned for {plugin,plugins}/*.{ts,js}
#    and the global config dir is the first of them. A plain .js file with
#    only node: imports loads with no npm install (measured, 1.19.3).
P=packages/opencode/src/config/plugin.ts
F=$(fetch $P)
if need "$F" $P; then
	has "$F" 'Glob.scan("{plugin,plugins}/*.{ts,js}"' || miss "plugins are no longer discovered as {plugin,plugins}/*.{ts,js} -- blink.js will not load"
	pass "plugin/*.js is still auto-discovered"
fi
P=packages/opencode/src/config/paths.ts
F=$(fetch $P)
if need "$F" $P; then
	has "$F" 'Global.Path.config,' || miss "the global config dir is no longer a plugin directory"
	pass "the global config dir is still scanned"
fi
P=packages/opencode/src/config/config.ts
F=$(fetch $P)
if need "$F" $P; then
	has "$F" 'ConfigPlugin.load(dir)' || miss "config dirs are no longer scanned for plugins"
	pass "every config dir is still scanned for plugins"
fi

# 4. The plugin API. blink.js exports one async function returning hooks, and
#    uses three of them: `event` for the bus, and tool.execute.before/after to
#    keep a long tool call's clock fresh. permission.ask is declared but never
#    called in 1.19.3, which is why the plugin listens for the
#    permission.asked EVENT and does not use that hook.
P=packages/plugin/src/index.ts
F=$(fetch $P)
if need "$F" $P; then
	has "$F" 'export type Plugin = (input: PluginInput' || miss "a plugin is no longer a function of PluginInput"
	has "$F" 'event?: (input: { event: Event }) => Promise<void>' || miss "the event hook's signature changed"
	has "$F" '"tool.execute.before"?:' || miss "the tool.execute.before hook is gone"
	has "$F" '"tool.execute.after"?:' || miss "the tool.execute.after hook is gone"
	pass "event, tool.execute.before and tool.execute.after are still hooks"
fi

# 5. Session status: the light. busy -> running, idle -> your turn, retry ->
#    running or failed depending on how far away `next` is (epoch ms). It is
#    in memory only -- nothing about a retry reaches the DB -- which is the
#    reason there is a plugin at all.
P=packages/schema/src/session-status-event.ts
F=$(fetch $P)
if need "$F" $P; then
	has "$F" 'type: "session.status",' || miss "the session.status event is renamed"
	for lit in idle retry busy; do
		has "$F" "type: Schema.Literal(\"$lit\")," || miss "session.status lost '$lit'"
	done
	has "$F" 'next: NonNegativeInt,' || miss "a retry no longer carries next -- a quota wait cannot be told from a blip"
	has "$F" 'status: Info,' || miss "session.status no longer carries status"
	pass "session.status is still busy/idle/retry, with retry.next"
fi

# 6. Sessions: created/updated carry info.parentID, which is how a subagent's
#    session is folded into its parent instead of lighting up as a second
#    session; deleted ends the slot; session.error carries error.name, and
#    MessageAbortedError (the person pressed Esc) is idle, not red.
P=packages/schema/src/v1/session.ts
F=$(fetch $P)
if need "$F" $P; then
	for ev in session.created session.updated session.deleted session.error; do
		has "$F" "type: \"$ev\"," || miss "the $ev event is renamed or gone"
	done
	has "$F" 'parentID: optional(SessionID),' || miss "a session no longer carries parentID -- subagents will show as sessions"
	has "$F" 'info: SessionInfo,' || miss "session events no longer carry info"
	has "$F" 'namedError("MessageAbortedError"' || miss "MessageAbortedError is renamed -- an Esc will paint the light red"
	pass "session events, parentID and MessageAbortedError are unchanged"
fi

# 7. Waiting on you. permission.asked / question.asked carry the request id
#    as `id`; the replies carry it as `requestID`. The plugin keeps the set of
#    open ids per session and clears the waiting marker when it empties.
P=packages/schema/src/v1/permission.ts
F=$(fetch $P)
if need "$F" $P; then
	has "$F" 'type: "permission.asked"' || miss "the permission.asked event is renamed"
	has "$F" 'type: "permission.replied",' || miss "the permission.replied event is renamed"
	has "$F" 'schema: { sessionID: SessionID, requestID: ID, reply: Reply },' || miss "permission.replied no longer carries sessionID/requestID"
	pass "permission.asked/replied are unchanged"
fi
P=packages/schema/src/v1/question.ts
F=$(fetch $P)
if need "$F" $P; then
	for ev in question.asked question.replied question.rejected; do
		has "$F" "type: \"$ev\"" || miss "the $ev event is renamed or gone"
	done
	has "$F" 'export const Rejected = Schema.Struct({ sessionID: SessionID, requestID: ID })' ||
		miss "question.rejected no longer carries sessionID/requestID"
	pass "question.asked/replied/rejected are unchanged"
fi

# 8. The credential. OpenCode 1.x keeps the Coding Plan key in
#    <data>/opencode/auth.json, {"zai-coding-plan": {"type": "api", "key": ...}}.
#    OpenCode dev (the 2.0 line) carries a migration,
#    20260805200742_import_legacy_credentials, that copies auth.json ONCE into
#    a `credential` table in opencode.db and never writes the file again.
#    pc/providers/opencode.py reads that table (_db_credentials) and, when it
#    holds no plan key, auth.json -- so at a ref with the migration, what is
#    checked is the table's shape, and at a ref without it, auth.json's.
P=packages/core/src/database/migration.gen.ts
F=$(fetch $P)
MOVED=no
if need "$F" $P; then
	if has "$F" 'import_legacy_credentials'; then
		MOVED=yes
		ok "credentials live in the SQLite credential table at this ref -- checking the table"
	else
		ok "credentials have not moved into the credential table"
	fi
fi
# SC2016: the backticks and the $type below are OpenCode's TypeScript, matched
# literally by grep -F. Single quotes are the point.
# shellcheck disable=SC2016
if [ "$MOVED" = yes ]; then
	# 8a. The table as a fresh install creates it (schema.gen.ts is the
	#     current schema in one piece, every migration applied). The reader
	#     selects integration_id and value and orders by active, then
	#     time_created, then id.
	P=packages/core/src/database/schema.gen.ts
	F=$(fetch $P)
	if need "$F" $P; then
		has "$F" 'CREATE TABLE \`credential\` (' || miss "there is no credential table in the schema -- find where 2.0 keeps keys now"
		for col in '\`id\` text PRIMARY KEY,' '\`integration_id\` text,' '\`value\` text NOT NULL,' '\`active\` integer,' '\`time_created\` integer NOT NULL,'; do
			has "$F" "$col" || miss "the credential table no longer has $col -- CREDENTIAL_QUERY reads it"
		done
		pass "the credential table still has id, integration_id, value, active, time_created"
	fi
	# 8b. The value is plain JSON, {"type": "key", "key": ...}. Plain is
	#     the whole premise: a value encrypted with a machine secret is one
	#     BLINK must not try to read at all.
	P=packages/core/src/credential/sql.ts
	F=$(fetch $P)
	if need "$F" $P; then
		has "$F" 'sqliteTable("credential", {' || miss "the credential table is renamed"
		has "$F" 'value: text({ mode: "json" }).$type<Credential.Value>().notNull(),' ||
			miss "credential.value is no longer plain JSON text -- check for encryption before reading it"
		pass "credential.value is still plain JSON text"
	fi
	P=packages/schema/src/credential.ts
	F=$(fetch $P)
	if need "$F" $P; then
		grep -A1 'type: Schema.Literal("key"),' "$F" | grep -qF 'key: Schema.String,' ||
			miss "a key credential is no longer {type: \"key\", key}"
		pass "a key credential is still {type: \"key\", key}"
	fi
	P=packages/core/src/database/migration/20260805200742_import_legacy_credentials.ts
	F=$(fetch $P)
	if need "$F" $P; then
		has "$F" 'Credential.Key.make({ type: "key", key: value.key' ||
			miss "an auth.json api key is no longer imported as {type: \"key\", key}"
		has "$F" 'const integrationID = id.replace(' ||
			miss "the import no longer uses the auth.json key as integration_id"
		pass "auth.json's api keys are imported as {type: \"key\"} under their provider id"
	fi
	# 8c. Which row is THE key, when an integration has several: Credential.list
	#     orders by active, time_created, id ascending; resolveConnections
	#     reverses it and the active connection is the first.
	P=packages/core/src/credential.ts
	F=$(fetch $P)
	if need "$F" $P; then
		has "$F" '.orderBy(asc(CredentialTable.active), asc(CredentialTable.time_created), asc(CredentialTable.id))' ||
			miss "credentials are no longer ordered by active, time_created, id -- CREDENTIAL_QUERY may read a key OpenCode does not use"
		pass "credentials are still ordered by active, time_created, id"
	fi
	P=packages/core/src/integration.ts
	F=$(fetch $P)
	if need "$F" $P; then
		has "$F" '.toReversed()' || miss "resolveConnections no longer reverses the credential list"
		has "$F" 'return resolveConnections(entry, yield* credentials.list(id))[0]' ||
			miss "the active connection is no longer the first of resolveConnections"
		pass "the active credential is still the last of Credential.list"
	fi
else
	P=packages/opencode/src/auth/index.ts
	F=$(fetch $P)
	if need "$F" $P; then
		has "$F" 'const file = path.join(Global.Path.data, "auth.json")' || miss "auth.json is no longer <data>/opencode/auth.json"
		grep -A1 'type: Schema.Literal("api"),' "$F" | grep -qF 'key: Schema.String,' ||
			miss "an api credential is no longer {type: \"api\", key}"
		pass "the key is still in auth.json as {type: \"api\", key}"
	fi
fi

# 9. Third parties: the provider ids and the quota endpoint's shape.
#    models.dev is where OpenCode gets its provider list, and the provider id
#    is the auth.json key and picks the host: zai-coding-plan -> api.z.ai,
#    zhipuai-coding-plan -> open.bigmodel.cn. CodexBar's zai.js is the most
#    widely run parser of /api/monitor/usage/quota/limit; our parser follows
#    it on the window codes (unit 3 x 5 = five hours, unit 6 x 1 = a week) and
#    on reading success/code from the BODY, since failures come back HTTP 200.
third() {
	case "$THIRD_PARTY" in
	fail) miss "$*" ;;
	*)
		printf '  warn %s\n' "$*" >&2
		WARNS=$((WARNS + 1))
		;;
	esac
}
if [ "$THIRD_PARTY" = skip ]; then
	printf '  skip models.dev and CodexBar (offline or OPENCODE_THIRD_PARTY=skip)\n'
else
	MD=https://raw.githubusercontent.com/anomalyco/models.dev/dev/providers
	for pair in zai-coding-plan=api.z.ai zhipuai-coding-plan=open.bigmodel.cn; do
		id=${pair%%=*}
		host=${pair#*=}
		T="$WORK/models-dev-$id.toml"
		if ! curl -fsSL "$MD/$id/provider.toml" -o "$T" 2>/dev/null; then
			third "models.dev has no provider '$id' -- the auth.json key we look for may have changed"
		elif ! grep -qF "api = \"https://$host/" "$T"; then
			third "models.dev's '$id' no longer points at $host -- the quota host mapping may be wrong"
		else
			ok "models.dev still has $id on $host"
		fi
	done

	Z="$WORK/codexbar-zai.js"
	if ! curl -fsSL https://raw.githubusercontent.com/steipete/CodexBar/main/Sources/CodexBarCore/Resources/Plugins/zai.js -o "$Z" 2>/dev/null; then
		third "could not fetch CodexBar's zai.js -- it moved; find it before trusting the quota parser"
	else
		group
		grep -qF '/api/monitor/usage/quota/limit' "$Z" || third "CodexBar no longer reads /api/monitor/usage/quota/limit"
		grep -qF 'root.success !== true || root.code !== 200' "$Z" || third "CodexBar no longer checks success/code in the body"
		grep -qF 'const multipliers = { 1: 1440, 3: 60, 5: 1, 6: 10080 };' "$Z" || third "CodexBar's window unit codes changed -- re-check (3,5) and (6,1)"
		grep -qF '"CREDIT_LIMIT"' "$Z" || third "CodexBar no longer knows CREDIT_LIMIT"
		pass "CodexBar still reads the quota endpoint the way our parser does"
	fi
fi

if [ "$MISSES" -gt 0 ]; then
	fail "$MISSES OpenCode assumption(s) broken at $REF -- see the lines above"
fi
printf 'PASS [opencode contract at %s]\n' "$REF"
