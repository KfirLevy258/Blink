"""The five-hour burn view for a Codex account with no five-hour window.

docs/plans/burn-5h.md, "Codex". Codex says it outright: a reading whose
rate_limits carry a weekly window and no five-hour one (the owner's Codex
Pro, 2026-11-01) marks the codex page, and its burn line counts output
tokens per turn from the same rollouts' token_count events. Every rollout
here is generated by tests/support/rollouts.py; none is captured.
"""
import json
import os

import pytest

from pc import burn_reader as br
from pc import ingest, protocol
from pc.bridge import BURN_HEARTBEAT_S, BURN_MIN_GAP_S, THEME_QUIET_S, Bridge
from pc.providers import base, codex_cli
from tests.support import rollouts as ro

Q = 1_793_430_000
NOW = Q + 600
LATER = br.SCAN_EVERY_S


def start(i, q=Q):
    return q - (19 - i) * 900


def sessions(home):
    return home / ".codex" / "sessions"


def reader(home, **kw):
    return br.CodexBurnReader(root=str(sessions(home)), **kw)


def rollout(home, name="rollout-a.jsonl"):
    return ro.rollout_path(sessions(home), name=name)


# ------------------------------------------------------------- the reader


def test_a_turn_lands_in_its_epoch_quarter_hour_once_and_without_reasoning(
        tmp_path):
    """The fixture's reasoning is a third of each output and inside it, as
    measured; the reader counts output_tokens and nothing on top."""
    ro.write(tmp_path, rollout(tmp_path), [
        ro.token_count(start(0), 7),                    # the oldest's first s
        ro.token_count(start(19) - 1, 307, 300),        # the bucket before
        ro.token_count(start(19) + 1, 1507, 1200),
    ], mtime=NOW - 5)

    q, b = reader(tmp_path).poll(NOW)

    assert q == Q and len(b) == 20
    assert (b[0], b[18], b[19]) == (7, 300, 1200)
    assert sum(b) == 1507


def test_a_turn_before_the_window_is_not_counted_but_sets_the_total(tmp_path):
    ro.write(tmp_path, rollout(tmp_path), [
        ro.token_count(start(0) - 1, 5000),             # outside the window
        ro.token_count(start(10), 5400, 400),
    ], mtime=NOW - 5)

    _, b = reader(tmp_path).poll(NOW)

    assert sum(b) == 400 and b[10] == 400


def test_a_repeated_token_count_is_not_counted_twice(tmp_path):
    """228 events on the owner's desk repeated the previous cumulative
    total; summing last_token_usage would count each turn twice."""
    turn = ro.token_count(start(19), 900, 900)
    ro.write(tmp_path, rollout(tmp_path), [
        turn, turn, ro.token_count(start(19) + 30, 900, 900,
                                   limits=ro.weekly_only()),
    ], mtime=NOW - 5)

    _, b = reader(tmp_path).poll(NOW)

    assert sum(b) == 900


def test_a_total_that_goes_down_counts_that_turn_and_carries_on(tmp_path):
    """A new count in the same file (a compaction, a new session): that
    event's own last_token_usage, then differences from it."""
    ro.write(tmp_path, rollout(tmp_path), [
        ro.token_count(start(5), 1000),
        ro.token_count(start(6), 120, 120),              # counted afresh
        ro.token_count(start(7), 200, 80),
    ], mtime=NOW - 5)

    _, b = reader(tmp_path).poll(NOW)

    assert (b[5], b[6], b[7]) == (1000, 120, 80)
    assert sum(b) == 1200


def test_events_without_usage_and_other_lines_are_passed_over(tmp_path):
    ro.write(tmp_path, rollout(tmp_path), [
        ro.agent_message(start(19), text='mentions "token_count" in text'),
        ro.token_count(start(19), 0, info=False, limits=ro.weekly_only()),
        {"timestamp": "no zone 2026-11-01", "type": "event_msg",
         "payload": {"type": "token_count", "info": {
             "total_token_usage": ro.usage(50),
             "last_token_usage": ro.usage(50)}}},
        ro.token_count(start(19), 600),
    ], mtime=NOW - 5)

    _, b = reader(tmp_path).poll(NOW)

    # The stampless line is not counted, but its total (50) is the
    # baseline the next difference is taken from.
    assert sum(b) == 550


def test_only_what_was_appended_is_read_and_counted(tmp_path):
    path = ro.write(tmp_path, rollout(tmp_path),
                    [ro.token_count(start(18), 1000)], mtime=NOW - 5)
    r = reader(tmp_path)
    assert sum(r.poll(NOW)[1]) == 1000

    ro.write(tmp_path, path, [ro.token_count(start(19), 1250, 250)],
             mtime=NOW + 1, append=True)
    _, b = r.poll(NOW + LATER)

    assert (b[18], b[19]) == (1000, 250)
    assert r.last.read_bytes < os.path.getsize(path)


def test_a_partial_last_line_waits_for_its_newline(tmp_path):
    path = ro.write(tmp_path, rollout(tmp_path),
                    [ro.token_count(start(19), 100)], mtime=NOW - 5)
    whole = (json.dumps(ro.token_count(start(19), 400, 300)) + "\n").encode()
    ro.write(tmp_path, path, [whole[:40]], mtime=NOW - 4, append=True)
    r = reader(tmp_path)
    assert sum(r.poll(NOW)[1]) == 100

    ro.write(tmp_path, path, [whole[40:]], mtime=NOW + 1, append=True)

    assert sum(r.poll(NOW + LATER)[1]) == 400


def test_a_file_read_again_from_its_start_counts_nothing_twice(tmp_path):
    lines = [ro.token_count(start(17), 500), ro.token_count(start(18), 800,
                                                            300)]
    path = ro.write(tmp_path, rollout(tmp_path), lines, mtime=NOW - 5)
    r = reader(tmp_path)
    assert sum(r.poll(NOW)[1]) == 800

    # Rewritten shorter and then grown past the old length: read from 0.
    ro.write(tmp_path, path, [lines[0]], mtime=NOW - 2)
    ro.write(tmp_path, path, [lines[1], ro.token_count(start(19), 1000, 200),
                              ro.agent_message(start(19))],
             mtime=NOW - 1, append=True)
    r.poll(NOW + LATER - 1)             # the walk that sees it shorter, maybe
    _, b = r.poll(NOW + 2 * LATER)

    assert (b[17], b[18], b[19]) == (500, 300, 200)


def test_a_cold_file_is_followed_from_its_end_and_its_next_turn_counted(
        tmp_path):
    """A session untouched past 5 h 15 min is not read; when it resumes the
    first event read has no known total before it, and counts its own
    last_token_usage."""
    cold = NOW - br.FOLLOW_S - 60
    path = ro.write(tmp_path, rollout(tmp_path),
                    [ro.token_count(cold - 100, 90_000)], mtime=cold)
    r = reader(tmp_path)
    assert sum(r.poll(NOW)[1]) == 0
    assert r.last.read_bytes == 0

    ro.write(tmp_path, path, [ro.token_count(start(19), 90_700, 700)],
             mtime=NOW + 1, append=True)

    assert sum(r.poll(NOW + LATER)[1]) == 700


