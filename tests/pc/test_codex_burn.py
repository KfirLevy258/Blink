# ------------------------------------------------------------- the bridge


_NO_FEED = dict(fetch_manifest=lambda: None, fetch_signed_manifest=lambda: None)
CAPS = ["svc", "theme", "edit_done", "burn"]


class TwoPages:
    """The bus's fetch with two marked pages, each line set by the test."""

    def __init__(self):
        self.lines = {"claude": protocol.burn("claude", Q, [0] * 19 + [10]),
                      "codex": protocol.burn("codex", Q, [0] * 19 + [20])}
        self.asked = {"claude": 0, "codex": 0}
        self.marked = ["claude", "codex"]

    def __call__(self):
        return protocol.usage(-1.0, None, 12.0, None, [], provider="claude",
                              p2="codex", p2_session_pct=-1.0,
                              p2_weekly_pct=21.0)

    def burn_pages(self):
        return list(self.marked)

    def burn(self, provider="claude"):
        self.asked[provider] += 1
        line = self.lines[provider]
        return None if line is None else json.loads(json.dumps(line))


def bridge(fetch, caps=CAPS):
    clock = [1000.0]
    sent = []
    b = Bridge(write_msg=lambda m: sent.append((clock[0], m)),
               fetch_usage=fetch, now=lambda: clock[0],
               wall=lambda: (1752444000, 0), **_NO_FEED)
    hello = {"t": "hello", "v": 2, "board_id": "ab", "fw": "1.4.0"}
    if caps is not None:
        hello["caps"] = caps
    b.on_message(hello)

    def ticks(seconds, every=2.0):
        end = clock[0] + seconds
        while clock[0] + every <= end + 1e-9:
            clock[0] += every
            b.poll_if_changed()
    return sent, ticks


def burns(sent, p=None):
    return [(t, m) for t, m in sent
            if m["t"] == "burn" and (p is None or m["p"] == p)]


def test_both_pages_get_their_line_on_the_first_tick_after_the_quiet():
    fetch = TwoPages()
    sent, ticks = bridge(fetch)
    assert burns(sent) == []

    ticks(THEME_QUIET_S)

    assert sorted(m["p"] for _, m in burns(sent)) == ["claude", "codex"]
    for _, m in burns(sent):
        assert protocol.encode_checked(m)       # fits the wire


def test_one_pages_changes_never_starve_the_others_heartbeat():
    """Claude changing on every tick goes out every 15 s; Codex, unchanged,
    still gets its heartbeat every minute, on its own clock."""
    fetch = TwoPages()
    sent, ticks = bridge(fetch)
    ticks(THEME_QUIET_S)
    for k in range(70):
        fetch.lines["claude"] = protocol.burn("claude", Q,
                                              [0] * 19 + [100 + k])
        ticks(2)

    claude = [t for t, _ in burns(sent, "claude")]
    codex = [t for t, _ in burns(sent, "codex")]
    assert len(claude) >= 9
    assert all(b - a >= BURN_MIN_GAP_S for a, b in zip(claude, claude[1:]))
    assert len(codex) == 3
    assert all(BURN_HEARTBEAT_S <= b - a < BURN_HEARTBEAT_S + 2
               for a, b in zip(codex, codex[1:]))


def test_a_page_that_loses_its_mark_stops_alone():
    fetch = TwoPages()
    sent, ticks = bridge(fetch)
    ticks(THEME_QUIET_S)
    fetch.marked = ["claude"]
    before = len(burns(sent, "codex"))

    ticks(150)

    assert len(burns(sent, "codex")) == before
    assert len(burns(sent, "claude")) >= 3
    fetch.marked = ["claude", "codex"]
    ticks(2)
    assert len(burns(sent, "codex")) == before + 1


def test_a_board_without_the_cap_is_sent_neither_and_nothing_is_read():
    for caps in (["svc", "theme", "edit_done"], None):
        fetch = TwoPages()
        sent, ticks = bridge(fetch, caps)
        ticks(200)
        assert burns(sent) == [] and fetch.asked == {"claude": 0, "codex": 0}


