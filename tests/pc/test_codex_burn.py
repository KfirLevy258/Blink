def poll_codex(home, now=NOW):
    return codex_cli.CodexCliProvider(
        root=str(sessions(home)), state_dir=str(home / "codex-state"),
        sweep=False).poll(now)


def usage_frames(frames):
    return [f for f in frames if f.src == codex_cli.SRC_ID]


def test_a_weekly_only_reading_marks_the_codex_page(tmp_path):
    ro.write(tmp_path, rollout(tmp_path), [
        ro.token_count(NOW - 60, 100, limits=ro.weekly_only(21.0))],
        mtime=NOW - 60)

    frames = usage_frames(poll_codex(tmp_path))

    assert len(frames) == 1
    assert frames[0].no_session_window is True
    assert frames[0].session_pct == -1 and frames[0].weekly_pct == 21.0


