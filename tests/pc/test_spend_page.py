def test_nothing_spend_related_is_printed(tmp_path, capfd, caplog,
                                          monkeypatch):
    caplog.set_level(logging.DEBUG)
    # Said once per process: as if this were the first failure.
    monkeypatch.setattr(claude_cli, "_spend_failed_said", False)
    clock = Clock(NOW)
    config(tmp_path, NOW - 60)
    bus = bus_on(clock)
    render(tmp_path, NOW - 30, 12.34, rate_limits=WINDOWS)
    bus.poll()
    render(tmp_path, NOW - 20, 13.00, rate_limits=WINDOWS)
    clock.t = NOW + 1
    bus.poll()

