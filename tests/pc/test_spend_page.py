def test_login_round_trip_restarts_the_count(tmp_path):
    clock = Clock(NOW)
    config(tmp_path, NOW - 3600, cache=False)
    bus = bus_on(clock)
    for at, cost in ((NOW, 1.00), (NOW + 10, 1.30)):
        render(tmp_path, at, cost, session="sess-a")
        clock.t = at + 1
        bus.poll()
    assert bus.plan_msg()["usd"] == 0.30

    # /login to Max: the page goes back to windows. Each switch is seen
    # on the poll after it (claude_plan.PlanReader.look), and the render
    # in the file then is the old login's (claude_cli._note_login), so
    # the new login renders after that poll.
    t = NOW + 100
    max_config(tmp_path, t)
    clock.t = t
    bus.poll()
    render(tmp_path, t, 4.00, session="sess-m", rate_limits=WINDOWS)
    clock.t = t + 1
    bus.poll()
    assert bus.plan_msg()["plan"] == "windows"

    # /login to another Enterprise seat: the count starts again.
    t = NOW + 200
    config(tmp_path, t, cache=False, acct=ACCT_B, org=ORG_B)
    clock.t = t
    bus.poll()
    for at, cost in ((t, 5.00), (t + 10, 5.10)):
        render(tmp_path, at, cost, session="sess-b")
        clock.t = at + 1
        bus.poll()
    assert bus.plan_msg()["plan"] == "spend"
    assert bus.plan_msg()["usd"] == 0.10

    # A restarted daemon over the same spend-count.json keeps B's count.
    t = NOW + 300
    clock.t = t
    bus2 = bus_on(clock)
    render(tmp_path, t, 5.25, session="sess-b")
    clock.t = t + 1
    bus2.poll()
    assert bus2.plan_msg()["usd"] == 0.25

    # And a restart signed in to A again finds B's count and drops it.
    t = NOW + 400
    config(tmp_path, t, cache=False)
    clock.t = t + 1
    bus3 = bus_on(clock)
    bus3.poll()
    assert bus3.plan_msg()["usd"] == 0.0


def test_a_login_away_and_back_takes_new_baselines(tmp_path):
    """/code-review max of 2026-11-04, U9: Claude Code keeps a session's id
    across /login but starts its cost again from zero. Back on the same
    seat, bind() keeps the count (same fingerprint) and the high-water
    marks with it, so every render under the old mark counted nothing:
    $0.30 of new spend shown as none. A login switch seen by the provider
    now drops the per-session marks (SpendCounter.forget_sessions), so the
    next sighting is a first one and the rises after it count."""
    clock = Clock(NOW)
    config(tmp_path, NOW - 3600, cache=False)
    bus = bus_on(clock)
    for at, cost in ((NOW, 1.00), (NOW + 10, 1.30)):
        render(tmp_path, at, cost, session="sess-a")
        clock.t = at + 1
        bus.poll()
    assert bus.plan_msg()["usd"] == 0.30
    # Each switch seen on the poll after it, before the new login renders
    # (test_login_round_trip_restarts_the_count).
    t = NOW + 100
    max_config(tmp_path, t)
    clock.t = t
    bus.poll()
    render(tmp_path, t, 0.00, session="sess-a", rate_limits=WINDOWS)
    clock.t = t + 1
    bus.poll()
    assert bus.plan_msg()["plan"] == "windows"
    t = NOW + 200
    config(tmp_path, t, cache=False)
    clock.t = t
    bus.poll()
    for at, cost in ((t, 0.20), (t + 10, 0.50), (t + 20, 0.75)):
        render(tmp_path, at, cost, session="sess-a")
        clock.t = at + 1
        bus.poll()
    assert bus.plan_msg()["plan"] == "spend"
    assert bus.plan_msg()["usd"] == 0.85


