def test_running_daemon_rolls_over_on_the_first(tmp_path):
    before = NEXT_MONTH - 120                       # 23:58 on the 30th
    fetched = float(calendar.timegm((2026, 11, 28, 9, 0, 0)))
    clock = Clock(before)
    config(tmp_path, fetched, fetched=fetched)
    bus = bus_on(clock)
    render(tmp_path, before - 60, 1.50)
    bus.poll()
    assert bus.plan_msg()["lim"] == 250.0
    # Past midnight UTC on the 1st, the config untouched.
    for at, cost in ((NEXT_MONTH + 30, 2.00), (NEXT_MONTH + 90, 2.40)):
        render(tmp_path, at, cost)
        clock.t = at + 1
        msg = bus.poll()
    plan = bus.plan_msg()
    assert plan["usd"] == 0.40
    assert "lim" not in plan
    assert bus.claude_page().spend_hint is True
    next_next = float(calendar.timegm((2027, 1, 1, 0, 0, 0)))
    assert msg["session_resets_in_s"] == int(next_next - clock.t)


def _desktop(at):
    frame = base.NormalizedUsageFrame(
        provider="claude", src="desktop", observed_at=at, session_pct=41.0,
        weekly_pct=12.0)
    return types.SimpleNamespace(get_provider_id=lambda: "claude",
                                 poll=lambda now: [frame])


def test_fresher_desktop_sample_does_not_flip_the_page(tmp_path):
    clock = Clock(NOW)
    config(tmp_path, NOW - 600, fetched=NOW - 600)
    render(tmp_path, NOW - 300, 1.00, rate_limits=WINDOWS)
    bus = bus_on(clock)
    bus.add_provider(_desktop(NOW))
    msg = bus.poll()
    assert bus.plan_msg()["plan"] == "spend"
    assert bus.plan_msg()["usd"] == 12.34
    assert msg["session_pct"] == 4.9
    assert msg["weekly_pct"] == -1
    assert msg["src"] == claude_cli.SPEND_SRC_ID


def _proved_no_window(home):
    session_verdict.save(
        inside(home, session_verdict.verdict_path()),
        session_verdict.evidence(
            False, session_verdict.KIND_STATUSLINE_SUSTAINED, NOW - 600))


def test_saved_no_window_verdict_never_marks_a_spend_page(tmp_path):
    _proved_no_window(tmp_path)
    clock = Clock(NOW)
    config(tmp_path, NOW - 60)
    render(tmp_path, NOW - 30, 1.00, rate_limits=WEEKLY_ONLY)
    bus = bus_on(clock)
    bus.poll()
    page = bus.claude_page()
    assert page.plan == base.PLAN_SPEND
    assert page.no_session_window is False
    assert bus.burn_pages() == []


def test_no_token_burn_on_a_spend_page(tmp_path):
    _proved_no_window(tmp_path)
    asked = []
    reader = types.SimpleNamespace(
        poll=lambda now: asked.append(now) or (protocol.burn_quarter(now),
                                                 [7] * 20))
    clock = Clock(NOW)
    config(tmp_path, NOW - 60)
    render(tmp_path, NOW - 30, 1.00, rate_limits=WEEKLY_ONLY)
    bus = bus_on(clock, burn={"claude": reader})
    bus.poll()
    assert bus.burn() is None
    assert bus.burn_pages() == []
    assert asked == []


def test_login_round_trip_restarts_the_count(tmp_path):
    clock = Clock(NOW)
    config(tmp_path, NOW - 3600, cache=False)
    bus = bus_on(clock)
    for at, cost in ((NOW, 1.00), (NOW + 10, 1.30)):
        render(tmp_path, at, cost, session="sess-a")
        clock.t = at + 1
        bus.poll()
    assert bus.plan_msg()["usd"] == 0.30

    # /login to Max: the page goes back to windows.
    t = NOW + 100
    max_config(tmp_path, t)
    render(tmp_path, t, 4.00, session="sess-m", rate_limits=WINDOWS)
    clock.t = t + 1
    bus.poll()
    assert bus.plan_msg()["plan"] == "windows"

    # /login to another Enterprise seat: the count starts again.
    t = NOW + 200
    config(tmp_path, t, cache=False, acct=ACCT_B, org=ORG_B)
    for at, cost in ((t, 5.00), (t + 10, 5.10)):
        render(tmp_path, at, cost, session="sess-b")
        clock.t = at + 1
        bus.poll()
    assert bus.plan_msg()["plan"] == "spend"
    assert bus.plan_msg()["usd"] == 0.10

    # A restarted daemon over the same spend-count.json keeps B's count.
    t = NOW + 300
    clock.t = t
    bus2 = bus_on(clock)
    render(tmp_path, t, 5.25, session="sess-b")
    clock.t = t + 1
    bus2.poll()
    assert bus2.plan_msg()["usd"] == 0.25

    # And a restart signed in to A again finds B's count and drops it.
    t = NOW + 400
    config(tmp_path, t, cache=False)
    clock.t = t + 1
    bus3 = bus_on(clock)
    bus3.poll()
    assert bus3.plan_msg()["usd"] == 0.0


def test_no_weekly_on_a_spend_page(tmp_path):
    weekly_anchor.save(inside(tmp_path, weekly_anchor.anchor_path()),
                       NOW + 3 * 86400, NOW - 86400)
    clock = Clock(NOW)
    config(tmp_path, NOW - 60)
    render(tmp_path, NOW - 30, 1.00, rate_limits=WINDOWS)
    bus = bus_on(clock)
    for i in range(3):
        clock.t = NOW + i
        msg = bus.poll()
    assert msg["weekly_pct"] == -1
    assert msg["weekly_resets_in_s"] == -1
    assert bus.plan_msg()["plan"] == "spend"


