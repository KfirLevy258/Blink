"""The spend page on the bus: Claude Code's saved usage plus the running
count, for a seat billed by usage (docs/plans/enterprise-spend.md, sections
1-2).

Every config and status line here is generated by this file, with made-up
ids and figures; nothing is captured from a machine. Each test drives the
shipped IngestionBus (its default providers, under tests/conftest.py's
sandboxed home) on a clock of its own, and reads the page back through
poll(), plan_msg() and claude_page().
"""
import calendar
import json
import logging
import os
import types

import pytest

from pc import (claude_plan, ingest, protocol, session_verdict,
                spend_count, weekly_anchor)
from pc import statusline_source as ss
from pc.providers import base, claude_cli
from tests.support.home import inside

# The 15th of a month, at noon UTC: the middle of a period.
NOW = float(calendar.timegm((2026, 11, 15, 12, 0, 0)))
NEXT_MONTH = float(calendar.timegm((2026, 12, 1, 0, 0, 0)))
ACCT, ORG = "ACCT-SPEND-7f3a20", "ORG-SPEND-91c2d4"
ACCT_B, ORG_B = "ACCT-SPEND-b0b0b0", "ORG-SPEND-b1b1b1"
ACCT_MAX, ORG_MAX = "ACCT-MAX-55aa55", "ORG-MAX-66bb66"


def config(home, at, *, seat="enterprise_usage_based", billing=None,
           used=1234, limit=25000, enabled=True, fetched=None, cache=True,
           acct=ACCT, org=ORG, org_type="claude_enterprise", raw=None):
    """Write Claude Code's config where claude_plan looks, mtime `at`.
    `fetched` is the /usage time (epoch s), default a minute before `at`."""
    path = inside(home, claude_plan.config_path())
    if raw is None:
        oauth = {"accountUuid": acct, "organizationUuid": org,
                 "organizationType": org_type}
        if seat is not None:
            oauth["seatTier"] = seat
        if billing is not None:
            oauth["billingType"] = billing
        doc = {"oauthAccount": oauth, "projects": {"/srv/demo": {}}}
        if cache:
            doc["cachedUsageUtilization"] = {
                "fetchedAtMs": int(((at - 60) if fetched is None
                                    else fetched) * 1000),
                "accountUuid": acct,
                "utilization": {"extra_usage": {
                    "is_enabled": enabled, "monthly_limit": limit,
                    "used_credits": used, "utilization": 4.9,
                    "currency": "usd"}}}
        raw = json.dumps(doc)
    with open(path, "w", encoding="utf-8") as f:
        f.write(raw)
    os.utime(path, (at, at))
    return path


def max_config(home, at):
    return config(home, at, seat="max", billing="subscription", cache=False,
                  acct=ACCT_MAX, org=ORG_MAX, org_type="claude_max")


WINDOWS = {"five_hour": {"used_percentage": 41.0, "resets_at": NOW + 3600},
           "seven_day": {"used_percentage": 12.0,
                         "resets_at": NOW + 3 * 86400}}
WEEKLY_ONLY = {"seven_day": {"used_percentage": 12.0,
                             "resets_at": NOW + 3 * 86400}}


def render(home, at, cost, session="sess-a", rate_limits=None):
    """One status-line render, as the shim leaves it, dated `at`."""
    path = inside(home, ss.payload_path())
    os.makedirs(os.path.dirname(path), exist_ok=True)
    payload = {"session_id": session, "model": {"id": "m"},
               "cost": {"total_cost_usd": cost}}
    if rate_limits is not None:
        payload["rate_limits"] = rate_limits
    with open(path, "w", encoding="utf-8") as f:
        json.dump(payload, f)
    os.utime(path, (at, at))


class Clock:
    def __init__(self, t):
        self.t = t

    def __call__(self):
        return self.t


def bus_on(clock, **kw):
    return ingest.IngestionBus(now=clock, **kw)


def count_path(home):
    return os.path.join(str(home), ".blink", "spend-count.json")


def test_spend_seat_gives_a_spend_plan_message(tmp_path):
    clock = Clock(NOW)
    config(tmp_path, NOW - 60, fetched=NOW - 60)
    bus = bus_on(clock)
    msg = bus.poll()
    plan = bus.plan_msg()
    assert plan["plan"] == "spend"
    assert plan["p"] == "claude"
    assert plan["period"] == "monthly"
    assert plan["usd"] == 12.34
    assert plan["lim"] == 250.0
    page = bus.claude_page()
    assert page.src == claude_cli.SPEND_SRC_ID
    assert page.spend_exact is True
    assert page.spend_hint is False
    assert msg["session_pct"] == 4.9
    assert msg["session_resets_in_s"] == int(NEXT_MONTH - NOW)


def test_rises_after_the_anchor_add_up(tmp_path):
    clock = Clock(NOW - 499)
    config(tmp_path, NOW - 600, used=1000, fetched=NOW - 600)
    bus = bus_on(clock)
    for at, cost in ((NOW - 500, 1.00), (NOW - 400, 1.50),
                     (NOW - 300, 1.75)):
        render(tmp_path, at, cost)
        clock.t = at + 1
        bus.poll()
    plan = bus.plan_msg()
    assert plan["plan"] == "spend"
    assert plan["usd"] == 10.75
    assert plan["lim"] == 250.0
    page = bus.claude_page()
    assert page.spend_exact is False
    # Dated by the newest render, not by the /usage before it.
    assert page.observed_at == NOW - 300


def test_no_cache_shows_the_count_with_the_hint(tmp_path):
    clock = Clock(NOW)
    config(tmp_path, NOW - 3600, cache=False)
    bus = bus_on(clock)
    seen = []
    for i, cost in enumerate((1.00, 1.20, 1.45)):
        at = NOW + 10 * i
        render(tmp_path, at, cost)
        clock.t = at + 1
        msg = bus.poll()
        seen.append(bus.plan_msg()["plan"])
        assert msg is not None
    assert seen == ["spend"] * 3
    plan = bus.plan_msg()
    assert plan["usd"] == 0.45
    assert "lim" not in plan
    page = bus.claude_page()
    assert page.spend_hint is True and page.spend_exact is False
    assert msg["session_pct"] == -1


def test_an_old_anchor_shows_the_hint(tmp_path):
    clock = Clock(NOW)
    config(tmp_path, NOW - 2 * 86400, fetched=NOW - 2 * 86400)
    bus = bus_on(clock)
    bus.poll()
    page = bus.claude_page()
    assert page.spend_hint is True and page.spend_exact is False
    assert bus.plan_msg()["lim"] == 250.0


