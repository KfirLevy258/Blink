def test_running_daemon_rolls_over_on_the_first(tmp_path):
    before = NEXT_MONTH - 120                       # 23:58 on the 30th
    fetched = float(calendar.timegm((2026, 11, 28, 9, 0, 0)))
    clock = Clock(before)
    config(tmp_path, fetched, fetched=fetched)
    bus = bus_on(clock)
    render(tmp_path, before - 60, 1.50)
    bus.poll()
    assert bus.plan_msg()["lim"] == 250.0
    # Past midnight UTC on the 1st, the config untouched.
    for at, cost in ((NEXT_MONTH + 30, 2.00), (NEXT_MONTH + 90, 2.40)):
        render(tmp_path, at, cost)
        clock.t = at + 1
