def test_a_gateway_spend_frame_wins(tmp_path):
    """The gateway's own figure, when the status line carries one, is the
    page; the config's anchor does not compete with it."""
    clock = Clock(NOW)
    config(tmp_path, NOW - 60)
    gateway = {"spend_limit": {"used_percentage": 62.8,
                               "resets_at": NEXT_MONTH, "used_usd": 314.12,
                               "limit_usd": 500, "period": "monthly"}}
    render(tmp_path, NOW - 30, 1.00, rate_limits=gateway)
    bus = bus_on(clock)
    msg = bus.poll()
    assert msg["session_pct"] == 62.8
    assert bus.plan_msg()["usd"] == 314.12
    assert bus.claude_page().src == ss.SRC_ID


def test_status_wire_does_not_save_the_count(tmp_path, capsys):
    """`blink status --wire` runs a whole bus on the real clock; it counts
    in memory and leaves the daemon's file alone."""
    import time
    from pc import cli
    real = time.time()
    config(tmp_path, real - 3600, cache=False)
    render(tmp_path, real - 60, 1.00)
    cli._wire_line()
    render(tmp_path, real - 30, 1.50)
    cli._wire_line()
    capsys.readouterr()
    assert not os.path.exists(count_path(tmp_path))


def test_status_provider_counts_in_memory_only(tmp_path):
    config(tmp_path, NOW - 3600, cache=False)
    p = claude_cli.ClaudeCliProvider()
    for at, cost in ((NOW, 1.00), (NOW + 10, 1.30)):
        render(tmp_path, at, cost)
        frames = p.poll(at + 1)
    spend = [f for f in frames if f.src == claude_cli.SPEND_SRC_ID]
    assert len(spend) == 1 and spend[0].spend_usd == pytest.approx(0.30)
    assert not os.path.exists(count_path(tmp_path))


FORBIDDEN = ("1234", "12.34", "enterprise_usage_based", "usage_based",
             ACCT, ORG, ACCT_B, ORG_B)


def test_nothing_spend_related_is_printed(tmp_path, capfd, caplog,
                                          monkeypatch):
    caplog.set_level(logging.DEBUG)
    # Said once per process: as if this were the first failure.
    monkeypatch.setattr(claude_cli, "_spend_failed_said", False)
    clock = Clock(NOW)
    config(tmp_path, NOW - 60)
    bus = bus_on(clock)
    render(tmp_path, NOW - 30, 12.34, rate_limits=WINDOWS)
    bus.poll()
    render(tmp_path, NOW - 20, 13.00, rate_limits=WINDOWS)
    clock.t = NOW + 1
    bus.poll()

    # A misshapen config: every spend field the wrong type.
    t = NOW + 100
    config(tmp_path, t, raw=json.dumps({
        "oauthAccount": {"accountUuid": ACCT, "organizationUuid": ORG,
                         "seatTier": "enterprise_usage_based",
                         "billingType": ["usage_based"],
                         "organizationType": 1234},
        "cachedUsageUtilization": {
            "fetchedAtMs": "12.34", "accountUuid": [ACCT],
            "utilization": {"extra_usage": [1234, "usage_based"]}}}))
    clock.t = t + 1
    bus.poll()

    # And the spend path failing outright, with the figures in the error.
    def boom(self, *a, **k):
        raise ValueError(f"1234 12.34 enterprise_usage_based {ACCT} {ORG}")
    monkeypatch.setattr(spend_count.SpendCounter, "since", boom)
    t = NOW + 200
    config(tmp_path, t, acct=ACCT_B, org=ORG_B)
    for i in range(3):
        clock.t = t + 1 + i
        bus.poll()

    out = capfd.readouterr()
    text = out.out + out.err + caplog.text
    for word in FORBIDDEN:
        assert word not in text
    # The failure is said, once, in fixed words.
    assert out.err.count(claude_cli.SPEND_FAILED_MSG) == 1
