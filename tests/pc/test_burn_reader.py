def test_claude_config_dir_moves_the_transcripts(tmp_path, monkeypatch):
    """Claude Code keeps everything under CLAUDE_CONFIG_DIR when it is set.
    tests/conftest.py clears it for every test, the way it clears
    CODEX_HOME, so this sets it itself."""
    r = br.BurnReader()
    monkeypatch.setenv("CLAUDE_CONFIG_DIR", str(tmp_path / "work-config"))
    tx.write(tmp_path, tmp_path / "work-config" / "projects" / "p" / "s.jsonl",
             [a(1, start(19), 13)], mtime=NOW)
    tx.write(tmp_path, session(tmp_path), [a(2, start(19), 1000)], mtime=NOW)

    assert sum(r.poll(NOW)[1]) == 13
    assert br.transcripts_root() == str(tmp_path / "work-config" / "projects")


def test_without_claude_config_dir_it_is_under_home(tmp_path):
    assert br.transcripts_root() == str(tmp_path / ".claude" / "projects")
