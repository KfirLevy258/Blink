"""The burn view's reader: output tokens from Claude Code's transcripts.

docs/plans/burn-5h.md is the contract: twenty quarter-hour buckets on epoch
boundaries, output tokens only, read incrementally, de-duplicated on
(message.id, requestId), <synthetic> skipped, files untouched for more than
5 h 15 min ignored. Every transcript here is generated by
tests/support/transcripts.py; none is captured from a machine.
"""
import os

from pc import burn_reader as br
from tests.support import transcripts as tx
from tests.support.home import inside

Q = 1_793_430_000           # the contract's own example, a quarter-hour
NOW = Q + 600               # ten minutes into it
LATER = br.SCAN_EVERY_S     # far enough on for the next walk


def start(i, q=Q):
    """Where bucket i (0 = oldest) starts, by the contract's formula."""
    return q - (19 - i) * 900


def projects(home):
    return home / ".claude" / "projects"


def reader(home, **kw):
    return br.BurnReader(root=str(projects(home)), **kw)


def session(home, name="s"):
    return projects(home) / "-work-project" / (name + ".jsonl")


def a(i, at, tokens, **kw):
    """Assistant message number i, with its own id and request."""
    return tx.assistant("msg_%04d" % i, "req_%04d" % i, at, tokens, **kw)


