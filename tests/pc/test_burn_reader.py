def test_garbage_never_raises_never_counts_and_says_nothing(tmp_path,
                                                            capsys):
    def with_tokens(value):
        line = a(50, start(19), 1)
        line["message"]["usage"]["output_tokens"] = value
        return line

    def with_stamp(value):
        line = a(51, start(19), 1)
        line["timestamp"] = value
        return line

    no_id = a(52, start(19), 1)
    del no_id["message"]["id"]
    bad_message = a(53, start(19), 1)
    bad_message["message"] = "MARKER-not-a-message"
    bad_usage = a(54, start(19), 1)
    bad_usage["message"]["usage"] = ["MARKER-not-a-dict"]
    garbage = [
        b'{"output_tokens": MARKER-not-json\n',
        b'\xff\xfe"output_tokens"\x80\n',
        b'["output_tokens", 1]\n',
        b'{"output_tokens":' + b"[" * 100_000 + b"]" * 100_000 + b"}\n",
        with_tokens("12"), with_tokens(True), with_tokens(-5),
        with_tokens(1.5), with_tokens(None),
        with_stamp("2026-13-01T00:00:00.000Z"),
        with_stamp("2026-10-31T10:15:00"),
        with_stamp("MARKER-not-a-date"), with_stamp(1793430000),
        no_id, bad_message, bad_usage,
    ]
    tx.write(tmp_path, session(tmp_path), garbage, mtime=NOW)

    got = reader(tmp_path).poll(NOW)

    assert got == (Q, [0] * 20)
    out, err = capsys.readouterr()
    assert out == "" and err == ""


def test_a_file_that_cannot_be_opened_is_tried_again(tmp_path, monkeypatch,
                                                     capsys):
    """And says nothing: an OSError's text is the transcript's path, which
    names the customer's project."""
    tx.write(tmp_path, session(tmp_path), [a(1, start(19), 8)], mtime=NOW)
    r = reader(tmp_path)
    real_open = open

    def refuse(path, *args, **kwargs):
        if str(path).endswith(".jsonl"):
            raise PermissionError(13, "MARKER-permission", str(path))
        return real_open(path, *args, **kwargs)

    monkeypatch.setattr("builtins.open", refuse)
    assert r.poll(NOW) is None          # owed, not zero
    monkeypatch.setattr("builtins.open", real_open)

    assert sum(r.poll(NOW + 1)[1]) == 8
    assert capsys.readouterr() == ("", "")


def test_a_file_that_never_opens_stops_holding_the_view_back(tmp_path,
                                                            monkeypatch):
    """One transcript left owned by another user must not cost a desk the
    whole view: after OPEN_TRIES refusals the sum goes out without it, and
    it is still counted the moment it opens."""
    tx.write(tmp_path, session(tmp_path, "locked"), [a(1, start(19), 8)],
             mtime=NOW)
    tx.write(tmp_path, session(tmp_path, "open"), [a(2, start(19), 5)],
             mtime=NOW)
    r = reader(tmp_path)
    real_open = open

    def refuse(path, *args, **kwargs):
        if str(path).endswith("locked.jsonl"):
            raise PermissionError(13, "denied", str(path))
        return real_open(path, *args, **kwargs)

    monkeypatch.setattr("builtins.open", refuse)
    got = [r.poll(NOW + k) for k in range(br.OPEN_TRIES)]
    assert got[:-1] == [None] * (br.OPEN_TRIES - 1)
    assert sum(got[-1][1]) == 5
    monkeypatch.setattr("builtins.open", real_open)

    assert sum(r.poll(NOW + br.OPEN_TRIES)[1]) == 13


