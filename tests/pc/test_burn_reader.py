def test_a_message_lands_in_its_epoch_quarter_hour(tmp_path):
    tx.write(tmp_path, session(tmp_path), [
        a(1, start(19) + 1, 1200),
        a(2, start(19) - 1, 300),       # the last second of the bucket before
        a(3, start(0), 7),              # the oldest bucket's first second
    ], mtime=NOW - 5)

    q, b = reader(tmp_path).poll(NOW)

    assert q == Q and q % 900 == 0
    assert len(b) == 20
    assert (b[0], b[18], b[19]) == (7, 300, 1200)
    assert sum(b) == 1507


