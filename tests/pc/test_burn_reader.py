def test_an_offset_timestamp_is_read_as_the_utc_instant_it_names(tmp_path):
    line = a(1, start(19), 64)
    # The same instant, written in India's offset: 5:30 later on the clock.
    line["timestamp"] = tx.stamp(start(19) + 5.5 * 3600).replace(
        "Z", "+05:30")
    tx.write(tmp_path, session(tmp_path), [line], mtime=NOW)

    _, b = reader(tmp_path).poll(NOW)

    assert b[19] == 64


