# ------------------------------------------------------------- cost bound


def test_a_cold_backlog_is_read_a_budget_at_a_time_and_shown_only_whole(
        tmp_path):
    """A cold start owes every file touched in the window -- 225 MB on the
    dev desk. Each poll pays at most the budget (finishing the line it is
    in), and nothing is reported until the whole sum is in, so the board
    never shows a total that is still being added up."""
    filler = "x" * 2000
    lines = []
    for n in range(300):
        lines.append(tx.user(start(n % 20), text=filler))
        lines.append(a(n, start(n % 20), 1000))
    tx.write(tmp_path, session(tmp_path), lines, mtime=NOW)
    size = os.path.getsize(session(tmp_path))
    budget = 64 * 1024
    r = reader(tmp_path, read_budget=budget, chunk_bytes=8 * 1024)

    polls = []
    got = None
    for k in range(200):
        got = r.poll(NOW + k)
        polls.append(r.last)
        if got is not None:
            break

    assert got is not None and sum(got[1]) == 300_000
    assert all(p.read_bytes <= budget + 8 * 1024 for p in polls)
    assert len(polls) >= size // (budget + 8 * 1024)
    assert all(p.behind_bytes > 0 for p in polls[:-1])
    assert polls[-1].behind_bytes == 0


def test_a_line_longer_than_a_chunk_is_read_whole(tmp_path):
    tx.write(tmp_path, session(tmp_path),
             [a(1, start(19), 42, text="y" * 50_000), a(2, start(19), 1)],
             mtime=NOW)

    r = reader(tmp_path, chunk_bytes=1024, read_budget=1024)
    got = None
    for k in range(200):
        got = r.poll(NOW + k)
        if got is not None:
            break

    assert sum(got[1]) == 43


def test_an_over_long_line_is_skipped_and_reading_goes_on(tmp_path):
    """MAX_LINE_BYTES bounds what one line can hold in memory. A longer one
    is passed over, not held until it fits, which it never would."""
    tx.write(tmp_path, session(tmp_path),
             [a(1, start(19), 42, text="y" * 50_000), a(2, start(19), 1)],
             mtime=NOW)

    got = reader(tmp_path, chunk_bytes=1024, max_line_bytes=4096).poll(NOW)

    assert sum(got[1]) == 1


def test_a_line_passed_over_still_vouches_for_the_offset_after_it(tmp_path):
    """The anchor is the bytes before the offset whichever way they were
    taken, a skipped line's included: kept wrong, every append after an
    over-long last line would read the whole file again."""
    p = tx.write(tmp_path, session(tmp_path),
                 [a(1, start(19), 2), a(2, start(19), 42, text="y" * 50_000)],
                 mtime=NOW)
    r = reader(tmp_path, chunk_bytes=1024, max_line_bytes=4096)
    assert sum(r.poll(NOW)[1]) == 2

    tx.write(tmp_path, p, [a(3, start(19), 1)], mtime=NOW + 1, append=True)

    assert sum(r.poll(NOW + LATER)[1]) == 3
    assert r.last.read_bytes == (len(tx.encode(a(3, start(19), 1)))
                                 + br.ANCHOR_BYTES)


