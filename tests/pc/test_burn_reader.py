def test_a_line_from_before_the_window_does_not_count(tmp_path):
    tx.write(tmp_path, session(tmp_path), [a(1, start(0) - 1, 999),
                                           a(2, start(0), 1)], mtime=NOW)

    _, b = reader(tmp_path).poll(NOW)

    assert sum(b) == 1


def test_the_window_slides_with_the_clock(tmp_path):
    tx.write(tmp_path, session(tmp_path), [a(1, start(0), 10),
                                           a(2, start(1), 20)], mtime=NOW)
    r = reader(tmp_path)
    r.poll(NOW)

    q, b = r.poll(NOW + 900)

    assert q == Q + 900
    assert b[0] == 20 and sum(b) == 20


def test_a_message_from_a_few_seconds_ahead_shows_when_its_quarter_comes(
        tmp_path):
    """Claude Code and the daemon share a clock, but a line can be stamped
    a moment before the daemon's quarter-hour turns. It is not lost."""
    tx.write(tmp_path, session(tmp_path), [a(1, Q + 900 + 2, 70)], mtime=NOW)
    r = reader(tmp_path)

    assert sum(r.poll(NOW)[1]) == 0
    assert r.poll(Q + 900 + 5)[1][19] == 70


def test_a_file_untouched_for_more_than_5h15m_is_not_read(tmp_path):
    """Its lines are all older than the window; reading them costs a cold
    read of a file that can be 66 MB (the dev desk's largest) for nothing.
    The fixture puts in-window stamps in it to prove it was not read."""
    p = tx.write(tmp_path, session(tmp_path), [a(1, start(19), 5000)],
                 mtime=NOW - br.FOLLOW_S - 1)

    assert sum(reader(tmp_path).poll(NOW)[1]) == 0
    assert br.FOLLOW_S == 5 * 3600 + 15 * 60

    # Resumed: only what the resumption added is read.
    r = reader(tmp_path)
    r.poll(NOW)
    tx.write(tmp_path, p, [a(2, start(19), 6)], mtime=NOW, append=True)
    assert sum(r.poll(NOW + LATER)[1]) == 6


def test_a_file_touched_just_inside_5h15m_is_read(tmp_path):
    tx.write(tmp_path, session(tmp_path), [a(1, start(0), 5)],
             mtime=NOW - br.FOLLOW_S + 60)

    assert sum(reader(tmp_path).poll(NOW)[1]) == 5


# ------------------------------------------------------- reading only what is new


def test_a_partial_last_line_is_held_back_until_it_is_finished(tmp_path):
    p = session(tmp_path)
    whole = tx.encode(a(1, start(19), 10))
    second = tx.encode(a(2, start(19), 20))
    tx.write(tmp_path, p, [whole, second[:40]], mtime=NOW)
    r = reader(tmp_path)

    assert sum(r.poll(NOW)[1]) == 10

    tx.write(tmp_path, p, [second[40:]], mtime=NOW + 1, append=True)
    assert sum(r.poll(NOW + LATER)[1]) == 30


def test_only_the_bytes_after_the_last_read_are_read(tmp_path):
    """Proved by changing what was already read, keeping its length: a
    reader that went back to the start would count the new first line."""
    p = session(tmp_path)
    tx.write(tmp_path, p, [a(1, start(19), 100)], mtime=NOW)
    r = reader(tmp_path)
    assert sum(r.poll(NOW)[1]) == 100

    same_length = tx.encode(a(9, start(19), 900))
    assert len(same_length) == len(tx.encode(a(1, start(19), 100)))
    tx.write(tmp_path, p, [same_length, a(2, start(19), 1)], mtime=NOW + 1)

    assert sum(r.poll(NOW + LATER)[1]) == 101
    assert r.last.read_bytes == len(tx.encode(a(2, start(19), 1)))


def test_a_poll_with_nothing_new_reads_nothing(tmp_path):
    for n in range(30):
        tx.write(tmp_path, session(tmp_path, "s%d" % n),
                 [a(n, start(19), 1)], mtime=NOW)
    r = reader(tmp_path)
    r.poll(NOW)

    r.poll(NOW + LATER)

    assert r.last.walked and r.last.read_bytes == 0 and r.last.files == 30


def test_a_truncated_file_is_read_again_from_the_start(tmp_path):
    p = session(tmp_path)
    tx.write(tmp_path, p, [a(1, start(19), 100), a(2, start(19), 200)],
             mtime=NOW)
    r = reader(tmp_path)
    r.poll(NOW)

    # Shorter than what was read: start over. What was counted stays
    # counted, because it happened; what is read again is not counted twice.
    tx.write(tmp_path, p, [a(1, start(19), 100)], mtime=NOW + 1)
    assert sum(r.poll(NOW + LATER)[1]) == 300
    tx.write(tmp_path, p, [a(3, start(19), 4)], mtime=NOW + 2, append=True)
    assert sum(r.poll(NOW + 2 * LATER)[1]) == 304


@pytest.mark.skipif(sys.platform == "win32",
                    reason="DirEntry.stat() has no inode on Windows")
def test_a_replaced_file_is_read_again_from_the_start(tmp_path):
    p = session(tmp_path)
    tx.write(tmp_path, p, [a(1, start(19), 100)], mtime=NOW)
    r = reader(tmp_path)
    r.poll(NOW)

    fresh = tmp_path / "fresh.jsonl"
    tx.write(tmp_path, fresh, [a(7, start(19), 5), a(1, start(19), 100),
                               a(2, start(19), 30)], mtime=NOW + 1)
    os.replace(fresh, p)

    assert sum(r.poll(NOW + LATER)[1]) == 135


def test_a_new_session_is_found_at_the_next_walk_and_not_before(tmp_path):
    """The walk is the per-file cost (a stat each, 14 ms for the dev desk's
    4401), so it runs once per SCAN_EVERY_S, not on every call."""
    tx.write(tmp_path, session(tmp_path, "first"), [a(1, start(19), 1)],
             mtime=NOW)
    r = reader(tmp_path)
    r.poll(NOW)
    tx.write(tmp_path, session(tmp_path, "second"), [a(2, start(19), 2)],
             mtime=NOW + 1)

    assert sum(r.poll(NOW + 1)[1]) == 1 and not r.last.walked
    assert sum(r.poll(NOW + LATER)[1]) == 3 and r.last.walked


