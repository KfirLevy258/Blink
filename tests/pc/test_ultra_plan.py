"""The Ultra fast path: one weekly-only reply, on an account whose Claude
Code config names the Ultra plan (owner's request, 2026-11-01: Ultra desks
switch on the first reply again).

The day before, the owner's Ultra desk showed the burn view within minutes;
after the sustained rule (claude_cli._reply_without_window) it needed about
five and a quarter hours of Claude Code use. Measured on that desk, field
names and these values only: oauthAccount.planDisplayName "Ultra",
organizationRateLimitTier "default_claude_max_20x", organizationType
"claude_max" (Claude Code 2.1.316). The plan is what rules Pro and Max out:
on them one weekly-only reply happens around a reset, so they never take
this path.

Every .claude.json here is generated by plan_doc(), with an invented
address and name standing in for the fields the real file also holds, so
a test can see they are not kept. Nothing is captured from a machine. The
writing helpers take their home from the caller (tests/support/home.py).
"""
import json
import logging
import os

import pytest

from pc import claude_plan, ingest, protocol, session_verdict
from pc.providers import claude_cli
from pc.providers.claude_cli import ClaudeCliProvider
from tests.pc.test_claude_cli import write
from tests.pc.test_no_session_window import NOW, replied, status
from tests.support.home import inside

ULTRA = session_verdict.KIND_STATUSLINE_ULTRA
SUSTAINED = session_verdict.KIND_STATUSLINE_SUSTAINED

# Stand-ins for what the real file holds beside the plan. Invented; a test
# below checks none of them is kept anywhere the reader can reach.
FAKE_EMAIL = "nobody-test@example.invalid"
FAKE_NAME = "Test Person Zzyzx"
FAKE_PROJECT = "/fixture/project-zzyzx"

MISSING = object()


def plan_doc(name="Ultra", tier="default_claude_max_20x",
             org="claude_max"):
    """A .claude.json of the measured shape. MISSING leaves a key out."""
    acct = {"emailAddress": FAKE_EMAIL, "displayName": FAKE_NAME,
            "organizationType": org}
    if name is not MISSING:
        acct["planDisplayName"] = name
    if tier is not MISSING:
        acct["organizationRateLimitTier"] = tier
    return {"numStartups": 12, "oauthAccount": acct,
            "projects": {FAKE_PROJECT: {"allowedTools": []}}}


def put_config(home, doc=None, raw=None, environ=None):
    """Write Claude Code's .claude.json where claude_plan.config_path()
    looks (under CLAUDE_CONFIG_DIR when `environ` sets it), inside the
    caller's `home` or not at all. `raw` is written as bytes instead."""
    path = inside(home, claude_plan.config_path(environ))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = raw if raw is not None else json.dumps(doc).encode("utf-8")
    with open(path, "wb") as f:
        f.write(data)
    return path


def one_reply(prov, p, at, five=None, cost=1.25, seven=2.0):
    """A session's first render a couple of minutes before `at`, then one
    reply at `at` (its cost risen), each polled a second after it is
    written. Returns the reply's live frame's evidence."""
    write(p, status(cost=1.0, seven=seven), at - 120)
    prov.poll(at - 119)
    doc = status(cost=cost, seven=seven, five=five,
                 five_resets=(at + 3600 if five is not None else None))
    write(p, doc, at)
    frames = prov.poll(at + 1)
    return frames[0].window_evidence if frames else None


# --- the fast path ------------------------------------------------------------


def test_ultra_plan_and_one_weekly_only_reply_marks_at_once(tmp_path):
    put_config(tmp_path, plan_doc())
    p = tmp_path / "statusline.json"
    prov = ClaudeCliProvider(path=str(p))

    assert one_reply(prov, p, NOW - 60) == (False, ULTRA, float(NOW - 60))


def test_the_bus_marks_the_page_and_saves_the_kind(tmp_path):
    """The whole way: the default plan path under HOME, the merged page
    marked on the first reply, and the verdict on disk under the new kind,
    which a fresh process loads."""
    put_config(tmp_path, plan_doc())
    p = tmp_path / "statusline.json"
    clock = [0.0]
    bus = ingest.IngestionBus(providers=[ClaudeCliProvider(path=str(p))],
                              now=lambda: clock[0])

    def poll(now):
        clock[0] = now
        msg = bus.poll()
        assert protocol.encode_checked(msg)[1] is None
        return msg

    write(p, status(cost=1.0), NOW - 120)
    poll(NOW - 119)
    assert bus.claude_page().no_session_window is False
    write(p, status(cost=1.25), NOW - 60)
    msg = poll(NOW - 59)

    assert bus.claude_page().no_session_window is True
    assert msg["session_pct"] == -1
    assert session_verdict.load(session_verdict.verdict_path()) == (
        False, ULTRA, float(NOW - 60))


@pytest.mark.parametrize("name,tier", [
    ("Ultra", "default_claude_max_20x"),
    ("  ultra ", MISSING),
    ("ULTRA", "default_claude_pro"),        # the name decides when present
    (MISSING, "default_claude_max_20x"),
    (None, "default_claude_max_20x"),
    ("", "default_claude_max_20x"),
    (MISSING, " DEFAULT_CLAUDE_MAX_20X "),
], ids=["measured", "trimmed", "upper", "no name, 20x tier",
        "null name", "blank name", "tier any case"])
def test_these_read_as_ultra(tmp_path, name, tier):
    put_config(tmp_path, plan_doc(name=name, tier=tier))
    p = tmp_path / "statusline.json"
    assert one_reply(ClaudeCliProvider(path=str(p)), p, NOW - 60) == (
        False, ULTRA, float(NOW - 60))


@pytest.mark.parametrize("name,tier", [
    ("Max", "default_claude_max_20x"),      # a name that is not Ultra wins
    ("Max", "default_claude_max_5x"),
    ("Pro", "default_claude_pro"),
    ("Max 5x", MISSING),
    ("Ultra Plus", MISSING),
    (MISSING, "default_claude_max_5x"),
    (MISSING, "default_claude_pro"),
    (MISSING, "max_20x_but_not_at_the_end"),
    (MISSING, MISSING),
    (7, "default_claude_max_20x"),          # a name of another type
    (MISSING, 20),
], ids=["max over a 20x tier", "max", "pro", "max 5x", "ultra plus",
        "5x tier", "pro tier", "20x not at the end", "neither",
        "number name", "number tier"])
def test_pro_and_max_never_take_the_fast_path(tmp_path, name, tier):
    """The case the sustained rule exists for: one weekly-only reply on a
    plan with windows -- a request streaming across a reset, or the last
    minutes of a window on a clock running fast. It proves nothing here."""
    put_config(tmp_path, plan_doc(name=name, tier=tier))
    p = tmp_path / "statusline.json"
    assert one_reply(ClaudeCliProvider(path=str(p)), p, NOW - 60) is None


def test_a_five_hour_render_on_ultra_is_a_window_not_a_mark(tmp_path):
    """An Ultra account not yet verified keeps a temporary five-hour limit.
    Its reply renders five_hour: window evidence, whatever the plan says."""
    put_config(tmp_path, plan_doc())
    p = tmp_path / "statusline.json"
    ev = one_reply(ClaudeCliProvider(path=str(p)), p, NOW - 60, five=30.0)
    assert ev == (True, session_verdict.KIND_STATUSLINE_WINDOW,
                  float(NOW - 60))


def test_a_five_hour_after_the_mark_clears_it_at_once(tmp_path):
    put_config(tmp_path, plan_doc())
    p = tmp_path / "statusline.json"
    clock = [0.0]
    bus = ingest.IngestionBus(providers=[ClaudeCliProvider(path=str(p))],
                              now=lambda: clock[0])
    for cost, at in ((1.0, NOW - 300), (1.25, NOW - 240)):
        write(p, status(cost=cost), at)
        clock[0] = at + 1
        bus.poll()
    assert bus.claude_page().no_session_window is True

    write(p, status(cost=1.5, five=12.0, five_resets=NOW + 3600), NOW - 60)
    clock[0] = NOW - 59
    msg = bus.poll()

    assert bus.claude_page().no_session_window is False
    assert msg["session_pct"] == 12.0
    assert session_verdict.load(session_verdict.verdict_path())[0] is True


def test_a_repaint_on_ultra_is_no_reply(tmp_path):
    """Cost unchanged since the session's last render: the status line was
    repainted, not replied to. No mark."""
    put_config(tmp_path, plan_doc())
    p = tmp_path / "statusline.json"
    prov = ClaudeCliProvider(path=str(p))
    assert one_reply(prov, p, NOW - 60, cost=1.0) is None


def test_a_first_render_on_ultra_is_no_reply(tmp_path):
    """No baseline: a session seen for the first time proves nothing."""
    put_config(tmp_path, plan_doc())
    p = write(tmp_path / "statusline.json", status(cost=4.0), NOW - 60)
    frames = ClaudeCliProvider(path=str(p)).poll(NOW)
    assert frames[0].window_evidence is None


def test_a_rise_against_an_old_baseline_on_ultra_is_no_reply(tmp_path):
    put_config(tmp_path, plan_doc())
    p = tmp_path / "statusline.json"
    prov = ClaudeCliProvider(path=str(p))
    old = NOW - 60 - claude_cli.BASELINE_MAX_S - 1
    write(p, status(cost=1.0), old)
    prov.poll(old + 1)
    write(p, status(cost=1.25), NOW - 60)
    assert prov.poll(NOW)[0].window_evidence is None


def test_an_unusable_weekly_on_ultra_is_no_reply(tmp_path):
    put_config(tmp_path, plan_doc())
    p = tmp_path / "statusline.json"
    prov = ClaudeCliProvider(path=str(p))
    write(p, status(cost=1.0), NOW - 120)
    prov.poll(NOW - 119)
    write(p, {"session_id": "s", "cost": {"total_cost_usd": 1.25},
              "rate_limits": {}}, NOW - 60)
    frames = prov.poll(NOW - 59)
    assert all(f.window_evidence is None for f in frames)


# --- a file that will not say -------------------------------------------------


BAD = {
    "corrupt": b"{",
    "a list": b"[]",
    "no account": json.dumps({"numStartups": 1}).encode(),
    "account not an object": json.dumps({"oauthAccount": "Ultra"}).encode(),
    "not utf-8": b'{"oauthAccount": {"planDisplayName": "\xff\xfe"}}',
    "nested deep": b"[" * 200000,
    "empty": b"",
}


@pytest.mark.parametrize("raw", list(BAD.values()), ids=list(BAD))
def test_a_file_that_will_not_read_falls_back_to_the_sustained_rule(
        tmp_path, raw):
    put_config(tmp_path, raw=raw)
    p = tmp_path / "statusline.json"
    prov = ClaudeCliProvider(path=str(p))
    assert one_reply(prov, p, NOW - 9 * 3600) is None
    got = replied(lambda now: prov.poll(now), p, NOW - 1)
    assert got[0].window_evidence == (False, SUSTAINED, float(NOW - 1))


def test_a_missing_file_falls_back_to_the_sustained_rule(tmp_path):
    assert not os.path.exists(claude_plan.config_path())
    p = tmp_path / "statusline.json"
    prov = ClaudeCliProvider(path=str(p))
    assert one_reply(prov, p, NOW - 9 * 3600) is None
    got = replied(lambda now: prov.poll(now), p, NOW - 1)
    assert got[0].window_evidence == (False, SUSTAINED, float(NOW - 1))


def test_an_unreadable_file_is_not_ultra(tmp_path):
    """A directory where the file should be: open() raises an OSError on
    every platform (IsADirectoryError, or PermissionError on Windows)."""
    os.makedirs(inside(tmp_path, claude_plan.config_path()))
    p = tmp_path / "statusline.json"
    assert one_reply(ClaudeCliProvider(path=str(p)), p, NOW - 60) is None


def test_a_file_over_the_cap_is_not_read(tmp_path):
    """Ultra in the first bytes, and too big to parse on the serial
    thread: not read, so not Ultra."""
    head = json.dumps(plan_doc())[:-1] + ', "pad": "'
    raw = (head + "x" * claude_plan.MAX_BYTES + '"}').encode()
    put_config(tmp_path, raw=raw)
    assert claude_plan.read(claude_plan.config_path()) is None
    p = tmp_path / "statusline.json"
    assert one_reply(ClaudeCliProvider(path=str(p)), p, NOW - 60) is None


def test_a_file_just_under_the_cap_is_read(tmp_path):
    head = json.dumps(plan_doc())[:-1] + ', "pad": "'
    pad = claude_plan.MAX_BYTES - len(head) - 2
    put_config(tmp_path, raw=(head + "x" * pad + '"}').encode())
    assert os.path.getsize(claude_plan.config_path()) == claude_plan.MAX_BYTES
    assert claude_plan.read(claude_plan.config_path()) is True


def test_a_read_that_raises_never_leaves_poll(tmp_path, monkeypatch):
    """Whatever the OS does to the stat, poll() returns."""
    def boom(*a, **k):
        raise PermissionError("denied")
    monkeypatch.setattr(claude_plan.os, "stat", boom)
    reader = claude_plan.PlanReader()
    assert reader.ultra(NOW) is False


