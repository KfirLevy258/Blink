"""The Ultra fast path: one weekly-only reply, on an account whose Claude
Code config names the Ultra plan (owner's request, 2026-11-01: Ultra desks
switch on the first reply again).

The day before, the owner's Ultra desk showed the burn view within minutes;
after the sustained rule (claude_cli._reply_without_window) it needed about
five and a quarter hours of Claude Code use. Measured on that desk, field
names and these values only: oauthAccount.planDisplayName "Ultra",
organizationRateLimitTier "default_claude_max_20x", organizationType
"claude_max" (Claude Code 2.1.316). The plan is what rules Pro and Max out:
on them one weekly-only reply happens around a reset, so they never take
this path.

Every .claude.json here is generated by plan_doc(), with an invented
address and name standing in for the fields the real file also holds, so
a test can see they are not kept. Nothing is captured from a machine. The
writing helpers take their home from the caller (tests/support/home.py).
"""
