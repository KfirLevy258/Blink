def test_the_bus_marks_the_page_and_saves_the_kind(tmp_path):
    """The whole way: the default plan path under HOME, the merged page
    marked on the first reply, and the verdict on disk under the new kind,
    which a fresh process loads."""
    put_config(tmp_path, plan_doc())
    p = tmp_path / "statusline.json"
    clock = [0.0]
    bus = ingest.IngestionBus(providers=[ClaudeCliProvider(path=str(p))],
                              now=lambda: clock[0])

    def poll(now):
        clock[0] = now
        msg = bus.poll()
        assert protocol.encode_checked(msg)[1] is None
        return msg

    write(p, status(cost=1.0), NOW - 120)
    poll(NOW - 119)
    assert bus.claude_page().no_session_window is False
    write(p, status(cost=1.25), NOW - 60)
    msg = poll(NOW - 59)

    assert bus.claude_page().no_session_window is True
    assert msg["session_pct"] == -1
    assert session_verdict.load(session_verdict.verdict_path()) == (
        False, ULTRA, float(NOW - 60))


