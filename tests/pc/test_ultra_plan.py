# --- how often, and what is kept ----------------------------------------------


def test_the_file_is_looked_at_once_a_minute_and_read_on_change(
        tmp_path, monkeypatch):
    path = put_config(tmp_path, plan_doc())
    reads = []
    real = claude_plan.read
    monkeypatch.setattr(claude_plan, "read",
                        lambda p: reads.append(1) or real(p))
    reader = claude_plan.PlanReader()

    assert reader.ultra(NOW) is True
    assert reader.ultra(NOW + 30) is True
    assert len(reads) == 1

    put_config(tmp_path, plan_doc(name="Max", tier="default_claude_max_5x"))
    os.utime(path, (NOW + 40, NOW + 40))
    assert reader.ultra(NOW + 59) is True       # not looked at yet
    assert reader.ultra(NOW + 60) is False      # looked at, changed, read
    assert len(reads) == 2
    assert reader.ultra(NOW + 200) is False     # looked at, unchanged
    assert len(reads) == 2


def test_a_clock_gone_back_looks_again(tmp_path):
    path = put_config(tmp_path, plan_doc())
    reader = claude_plan.PlanReader()
    assert reader.ultra(NOW) is True
    os.remove(path)
    assert reader.ultra(NOW - 3600) is False


def test_a_failed_read_is_tried_again_at_the_next_look(tmp_path,
                                                       monkeypatch):
    put_config(tmp_path, plan_doc())
    results = [None, True]
    monkeypatch.setattr(claude_plan, "read", lambda p: results.pop(0))
    reader = claude_plan.PlanReader()
    assert reader.ultra(NOW) is False
    assert reader.ultra(NOW + claude_plan.RECHECK_S) is True


def test_nothing_but_the_answer_is_kept_or_said(tmp_path, capsys, caplog):
    """The file holds an email address, a name and project paths. The
    reader keeps a boolean and the file's stamp, and says nothing."""
    caplog.set_level(logging.DEBUG)
    put_config(tmp_path, plan_doc())
    p = tmp_path / "statusline.json"
    prov = ClaudeCliProvider(path=str(p))
    assert one_reply(prov, p, NOW - 60)[1] == ULTRA

    kept = repr(vars(prov._plan)) + repr(vars(prov))
    for secret in (FAKE_EMAIL, FAKE_NAME, FAKE_PROJECT, "Ultra",
                   "max_20x", "claude_max"):
        assert secret not in kept
    out = capsys.readouterr()
    assert out.out == "" and out.err == ""
    assert caplog.records == []
    assert claude_plan.read(claude_plan.config_path()) is True


# --- the verdict and what is said about it --------------------------------------


def test_the_saved_kind_loads(tmp_path):
    path = inside(tmp_path, session_verdict.verdict_path())
    ev = session_verdict.evidence(False, ULTRA, NOW - 60)
    assert session_verdict.save(path, ev)
    assert session_verdict.load(path) == ev
    with open(path, encoding="utf-8") as f:
        assert json.load(f)["evidence"] == "statusline_ultra"
    v = session_verdict.SessionVerdict(path=path, persist=False)
    assert v.current() == ev
    assert v.observe([], NOW) is True


def test_the_kind_has_its_own_wording():
    assert session_verdict.DESCRIBE[ULTRA] == (
        "Claude Code reports an Ultra plan, and its replies come back"
        " without one")
    assert ULTRA in session_verdict.KINDS


def test_the_sustained_chain_still_names_itself_on_ultra(tmp_path):
    """A desk that completes the long proof is said to have done so, plan
    or no plan: that proof does not rest on a file Claude Code rewrites."""
    put_config(tmp_path, plan_doc())
    p = tmp_path / "statusline.json"
    prov = ClaudeCliProvider(path=str(p))
    got = replied(lambda now: prov.poll(now), p, NOW - 1)
    assert got[0].window_evidence == (False, SUSTAINED, float(NOW - 1))


