# --- the record install leaves for the service (found in review, 2026-10-19) --
#
# The service starts without the shell's XDG variables, so a desk that moves
# OpenCode with them had a daemon looking in ~/.local/share and finding
# nothing, while install and status, run from the shell, said all was well.


def test_the_record_carries_the_shells_xdg_view_to_the_service(
        tmp_path, monkeypatch):
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "d"))
    monkeypatch.setenv("XDG_CONFIG_HOME", str(tmp_path / "c"))
    assert "recorded" in opencode.record_dirs()
    want_data = os.path.join(str(tmp_path / "d"), "opencode")
    want_config = os.path.join(str(tmp_path / "c"), "opencode")
    # The service: no variables at all.
    monkeypatch.delenv("XDG_DATA_HOME")
    monkeypatch.delenv("XDG_CONFIG_HOME")
    assert opencode.data_dir() == want_data
    assert opencode.config_dir() == want_config
    assert opencode.service_dirs() == (want_data, want_config)
    path = opencode.paths_record_path()
    assert path == os.path.join(str(tmp_path), ".blink",
                                "opencode-paths.json")
    if os.name != "nt":
        assert os.stat(path).st_mode & 0o777 == 0o600
    assert not [n for n in os.listdir(os.path.dirname(path))
                if n.endswith(".tmp")]


def test_a_variable_in_this_shell_outranks_the_record(tmp_path, monkeypatch):
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "d"))
    opencode.record_dirs()
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "e"))
    assert opencode.data_dir() == os.path.join(str(tmp_path / "e"),
                                               "opencode")
    # And the service, which has no variable, still goes by the record.
    assert opencode.service_dirs()[0] == os.path.join(str(tmp_path / "d"),
                                                      "opencode")


