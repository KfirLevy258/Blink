def test_an_install_at_the_defaults_removes_an_old_record(tmp_path,
                                                          monkeypatch):
    """A record from an install under another environment would point the
    service at a directory this shell no longer uses."""
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path / "d"))
    opencode.record_dirs()
    monkeypatch.delenv("XDG_DATA_HOME")
