# --- the second ring goes to the tool used last (found in review, 2026-10-19)
#
# Every state frame used to carry active_at = now, so any provider with a
# slot under an hour old claimed to have been used this second; the ring
# tied, the stable sort kept poll order, and Codex -- polled before
# OpenCode -- held it. These run the real providers on generated files.


def _codex_used(root, state_dir, at):
    """A Codex session whose turn finished at `at`, its rollout last
    written then: what codex_cli reads, generated, never captured."""
    import datetime
    import json as _json

    def stamp(epoch):
        return datetime.datetime.fromtimestamp(
            epoch, datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")
    limits = {"limit_id": "codex",
              "primary": {"used_percent": 12.0, "resets_at": NOW + 3600,
                          "window_minutes": 300},
              "secondary": {"used_percent": 34.0, "resets_at": NOW + 86400,
                            "window_minutes": 10080}}
    path = os.path.join(root, "2026", "08", "27", "rollout-a.jsonl")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for doc in ({"timestamp": stamp(at - 30), "type": "event_msg",
                     "payload": {"type": "task_started"}},
                    {"timestamp": stamp(at - 1), "type": "event_msg",
                     "payload": {"type": "token_count", "info": {},
                                 "rate_limits": limits}},
                    {"timestamp": stamp(at), "type": "event_msg",
                     "payload": {"type": "task_complete"}}):
            f.write(_json.dumps(doc) + "\n")
    fx.stamp(path, at)
    from pc.providers import codex_cli
    return codex_cli.CodexCliProvider(root=root, state_dir=state_dir)


def _opencode_used(dirs, at, fetched_at=NOW - 30):
    """An OpenCode turn that finished at `at`, with a plan reading."""
    data, state = ready(dirs, active_at=at)
    fx.slot(state, "ses_oc", "Stop", at, name="glm")
    p = provider(dirs, Recorder(fx.encode(fx.credit_plan(NOW))))
    p.tick(fetched_at)
    return p


def _claude(at):
    class Fixed(base.ProviderParser):
        def get_provider_id(self):
            return "claude"

        def poll(self, now_epoch):
            return [base.NormalizedUsageFrame(
                provider="claude", src="cli", observed_at=at,
                session_pct=20.0, weekly_pct=10.0)]
    return Fixed()


def test_an_opencode_used_a_minute_ago_takes_the_ring_from_an_older_codex(
        dirs, tmp_path):
    codex = _codex_used(str(tmp_path / "sessions"),
                        str(tmp_path / "state-codex"), NOW - 50 * 60)
    oc = _opencode_used(dirs, NOW - 60)
    bus = ingest.IngestionBus(providers=[_claude(NOW - 5), codex, oc],
                              preferred_provider="claude", now=lambda: NOW)
    msg = bus.poll()
    assert (msg["provider"], msg["p2"]) == ("claude", "opencode")
    # Both sessions are still on the panel, ringed or not.
    assert msg["n_sess"] == 2


