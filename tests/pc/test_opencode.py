class Recorder:
    """A fetcher that records what it was asked and answers from a script."""

    def __init__(self, *answers):
        self.answers = list(answers)
        self.calls = []

    def __call__(self, url, key, timeout):
        self.calls.append((url, key, timeout))
        a = self.answers.pop(0) if len(self.answers) > 1 else self.answers[0]
        if isinstance(a, BaseException):
            raise a
        return a


def ready(dirs, active_at=NOW - 30, provider="zai-coding-plan"):
    """A desk where OpenCode has run, holds a plan key and was active."""
    data, state = dirs
