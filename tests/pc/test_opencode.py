    assert reads_per_fetch >= 1
    for t in range(5, 60, int(opencode.TICK_S)):      # eleven ticks, none due
        assert p.tick(NOW + t) is False
    assert auth.n == reads_per_fetch, "auth.json was read on a tick that did not fetch"
    assert p.tick(NOW + 60) is True
    assert auth.n == 2 * reads_per_fetch


