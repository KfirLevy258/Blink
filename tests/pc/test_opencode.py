class _CountingAuth:
    """Counts every read of auth.json, by wrapping the one function that
    opens it (_load_auth: quota_source and _read_key both go through it)."""

    def __init__(self, monkeypatch):
        self.n = 0
        real = opencode._load_auth

        def counted(*a, **k):
            self.n += 1
            return real(*a, **k)
        monkeypatch.setattr(opencode, "_load_auth", counted)


def test_auth_json_is_read_only_when_a_fetch_is_due(dirs, monkeypatch):
    """Found in review, 2026-10-19: tick() opened auth.json -- the file that
    holds every provider's token, not only the plan key -- on every 5 s
    tick, due or not. Now it is read only on the ticks that fetch."""
    ready(dirs, active_at=NOW)
    rec = Recorder(fx.encode(fx.credit_plan(NOW)))
    p = provider(dirs, rec)
    auth = _CountingAuth(monkeypatch)
    assert p.tick(NOW) is True
