"""Claude Code transcripts, invented line by line, for the burn reader.

CLAUDE.md: fixtures are generated by committed code, never captured from a
real machine, because a captured transcript carries somebody's real session
into a public repository. Everything here is made up: the ids are counters,
the text is filler, the project is /work/project. The shape follows what
pc/burn_reader reads (type, timestamp, message.id, requestId, message.model,
message.usage) and carries enough of the rest -- input and cache figures in
the same usage block, a parent uuid, a content array -- that a reader which
leaned on anything else would be caught out.

A writing helper takes its home from the caller and checks the path with
tests/support/home.inside before it writes; tests/pc/__init__.py says why.
"""
import datetime
import json
import os

from tests.support.home import inside

MODEL = "claude-opus-4-5"


def stamp(epoch):
    """An epoch as Claude Code writes `timestamp`: UTC, milliseconds, Z."""
    dt = datetime.datetime.fromtimestamp(epoch, datetime.timezone.utc)
    return dt.strftime("%Y-%m-%dT%H:%M:%S.") + "%03dZ" % (dt.microsecond
                                                        // 1000)


def assistant(msg_id, request_id, at, output_tokens, model=MODEL, text="ok",
              input_tokens=3, cache_read=200_000, cache_creation=1_500):
    """One assistant line. `request_id` None leaves the key out, as an API
    error line does. The cache figures are deliberately large: the reader
    must ignore them (docs/plans/burn-5h.md, output tokens only)."""
    line = {
        "parentUuid": "uuid-parent", "isSidechain": False,
        "userType": "external", "cwd": "/work/project",
        "sessionId": "session-0", "version": "2.0.0",
        "message": {
            "model": model, "id": msg_id, "type": "message",
            "role": "assistant",
            "content": [{"type": "text", "text": text}],
            "stop_reason": None, "stop_sequence": None,
            "usage": {"input_tokens": input_tokens,
                      "cache_creation_input_tokens": cache_creation,
                      "cache_read_input_tokens": cache_read,
                      "output_tokens": output_tokens,
                      "service_tier": "standard"},
        },
        "requestId": request_id, "type": "assistant",
        "uuid": "uuid-" + str(msg_id), "timestamp": stamp(at),
    }
    if request_id is None:
        del line["requestId"]
    return line


def user(at, text="a question about the project"):
    """One user line. A tool result is one of these, and the largest lines in
    a real transcript are tool results; `text` is how a test makes one big."""
    return {
        "parentUuid": "uuid-parent", "isSidechain": False,
        "userType": "external", "cwd": "/work/project",
        "sessionId": "session-0", "version": "2.0.0", "type": "user",
        "message": {"role": "user", "content": text},
        "uuid": "uuid-user-%d" % int(at), "timestamp": stamp(at),
    }


def encode(line):
    """A line as Claude Code appends it: compact JSON and a newline. Bytes
    pass through untouched, so a test can write a broken line on purpose."""
    if isinstance(line, (bytes, bytearray)):
        return bytes(line)
    return (json.dumps(line, separators=(",", ":")) + "\n").encode("utf-8")


def write(home, path, lines, mtime=None, append=False):
    """Write `lines` to the transcript at `path`, which must lie under
    `home`; append instead with append=True. `mtime` sets the file's
    modification time afterwards, which is how a test ages a file."""
    path = inside(home, path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "ab" if append else "wb") as f:
        for line in lines:
            f.write(encode(line))
    if mtime is not None:
        os.utime(path, (mtime, mtime))
    return path
