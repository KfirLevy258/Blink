"""Synthetic Claude Desktop folders for pc/desktop_chat_activity's tests.

Generated by this code, never captured: the real IndexedDB and its blob
folder hold conversations, and a captured copy would put somebody's chat in
a public repository. The bytes written here are random or made up; only
names, sizes and mtimes matter to the code under test, plus a Local Storage
analytics queue built from events the test spells out.

Every helper writes only under a root handed to make_layout() (a tmp_path),
and refuses any folder outside one (tests/support/home.inside), so a
scratch script that imports this cannot write into a real Desktop folder.
"""
import json
import os
import types

from tests.support import leveldb_fixture
from tests.support.home import inside

IDB_LEAF = ("IndexedDB", "https_claude.ai_0.indexeddb.leveldb")
BLOB_LEAF = ("IndexedDB", "https_claude.ai_0.indexeddb.blob")
LS_LEAF = ("Local Storage", "leveldb")

QUEUE_KEY = b"_https://claude.ai\x00\x01antalytics_queue_v1"

_ROOTS = []


def _checked(path):
    """`path`, once it lies under a root make_layout() was given."""
    for root in _ROOTS:
        try:
            return inside(root, path)
        except AssertionError:
            continue
    raise AssertionError(
        f"desktop_chat_fixtures asked to write outside every layout root: "
        f"{path}")


def make_layout(root, blob_subs=("1", "2")):
    """IndexedDB leveldb with one log, a blob folder with `blob_subs` (each
    holding one blob), and an empty Local Storage leveldb, under `root`."""
    root = str(root)
    if root not in _ROOTS:
        _ROOTS.append(root)
    ns = types.SimpleNamespace(
        root=root,
        idb_dir=os.path.join(root, *IDB_LEAF),
        blob_dir=os.path.join(root, *BLOB_LEAF),
        ls_dir=os.path.join(root, *LS_LEAF))
    for d in (ns.idb_dir, ns.blob_dir, ns.ls_dir):
        os.makedirs(_checked(d), exist_ok=True)
    with open(_checked(os.path.join(ns.idb_dir, "000003.log")), "wb") as fh:
        fh.write(os.urandom(64))
    for sub in blob_subs:
        add_blob(ns.blob_dir, sub, "1")
    return ns


def _logs(idb):
    nums = []
    for name in os.listdir(idb):
        stem, _, ext = name.partition(".")
        if ext == "log" and stem.isdigit():
            nums.append(int(stem))
    return sorted(nums)


def grow_log(idb, n_bytes):
    """Append `n_bytes` random bytes to the newest log."""
    newest = _logs(idb)[-1]
    path = _checked(os.path.join(idb, f"{newest:06d}.log"))
    with open(path, "ab") as fh:
        fh.write(os.urandom(n_bytes))


def rotate_log(idb, n_bytes=16):
    """Start the next-numbered log, the way a leveldb does after a flush."""
    nums = _logs(idb)
    nxt = (nums[-1] if nums else 0) + 1
    path = _checked(os.path.join(idb, f"{nxt:06d}.log"))
    with open(path, "wb") as fh:
        fh.write(os.urandom(n_bytes))


def add_blob(blob_dir, sub, name, n_bytes=32):
    """One new blob at <blob_dir>/<sub>/00/<name>."""
    folder = _checked(os.path.join(blob_dir, sub, "00"))
    os.makedirs(folder, exist_ok=True)
    with open(_checked(os.path.join(folder, name)), "wb") as fh:
        fh.write(os.urandom(n_bytes))


def rename_subfolders(blob_dir, mapping):
    """Rename top-level blob sub-folders, {old: new}."""
    for old, new in mapping.items():
        os.rename(_checked(os.path.join(blob_dir, old)),
                  _checked(os.path.join(blob_dir, new)))


def refuse_scandir(monkeypatch, module, path, exc=None):
    """Make `module.os.scandir` raise for `path` alone, while state["on"] is
    true. Done by patching rather than chmod so it runs on Windows and as
    root; it only ever raises, it never reads or names anything on disk."""
    real = os.scandir
    exc = exc or PermissionError(13, "refused")
    target = os.path.normcase(os.path.normpath(path))
    state = {"on": True, "hits": 0}

    def fake(p=".", *a, **k):
        if state["on"] and os.path.normcase(
                os.path.normpath(os.fspath(p))) == target:
            state["hits"] += 1
            raise exc
        return real(p, *a, **k)
    monkeypatch.setattr(module.os, "scandir", fake)
    return state


def queue_value(events):
    """The Local Storage value for an analytics queue of `events`, framed the
    way desktop_local_storage.decode_value reads it: \\x01 then UTF-8.
    `events` is a list of dicts, or any JSON value for a malformed case;
    a str is written as it is."""
    text = events if isinstance(events, str) else json.dumps(events)
    return b"\x01" + text.encode("utf-8")


def write_reading_file(root, blink_home, content):
    """Write <blink_home>/desktop_chat.json as the daemon would, or as a
    damaged copy would look: `content` is a dict (dumped as JSON) or a str
    (written as it is). `root` is the caller's tmp_path, and blink_home must
    lie under it (tests/support/home.inside), so this can never write into a
    real Blink folder. Returns the file's path."""
    from pc import desktop_chat_activity
    os.makedirs(inside(root, blink_home), exist_ok=True)
    path = inside(root, os.path.join(blink_home,
                                     desktop_chat_activity.READING_FILE))
    text = content if isinstance(content, str) else json.dumps(content)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return path


class FakeKernel32:
    """Stands in for kernel32 under desktop_chat_activity._load_kernel32,
    so the Windows writer check runs on macOS and Linux, where the suite
    does, with nothing real asked or touched.

    `procs` maps a pid to its exit code (desktop_chat_activity._STILL_ACTIVE
    for a running one); a pid not in it gets `open_error` from OpenProcess,
    ERROR_INVALID_PARAMETER (no such process) unless the test says
    otherwise. `exit_code_fails` makes GetExitCodeProcess return FALSE.
    Every call is recorded in `calls`, and `open_handles` is what has been
    opened and not closed."""

    def __init__(self, procs=None, open_error=87, exit_code_fails=False):
        self.procs = dict(procs or {})
        self.open_error = open_error
        self.exit_code_fails = exit_code_fails
        self.calls = []
        self.open_handles = set()
        self._last_error = 0
        self._next = 0x1000
        self._by_handle = {}

    def load(self):
        """What _load_kernel32 returns: (kernel32, get_last_error)."""
        return self, lambda: self._last_error

    def OpenProcess(self, access, inherit, pid):
        self.calls.append(("OpenProcess", access, inherit, pid))
        if pid not in self.procs:
            self._last_error = self.open_error
            return None                 # what restype c_void_p gives NULL
        self._next += 4
        self.open_handles.add(self._next)
        self._by_handle[self._next] = pid
        return self._next

    def GetExitCodeProcess(self, handle, code_ptr):
        self.calls.append(("GetExitCodeProcess", handle))
        if self.exit_code_fails:
            self._last_error = 6        # ERROR_INVALID_HANDLE
            return 0
        code_ptr.contents.value = self.procs[self._by_handle[handle]]
        return 1

    def CloseHandle(self, handle):
        self.calls.append(("CloseHandle", handle))
        self.open_handles.discard(handle)
        return 1


def write_queue(ls_dir, events, number=5):
    """Write (replace) the Local Storage log holding the analytics queue."""
    data = leveldb_fixture.build_log(
        [[("put", QUEUE_KEY, queue_value(events))]])
    path = _checked(os.path.join(ls_dir, f"{number:06d}.log"))
    with open(path, "wb") as fh:
        fh.write(data)
