"""Codex rollout lines, invented, for the Codex burn reader and its mark.

CLAUDE.md: fixtures are generated by committed code, never captured from a
real machine. Everything here is made up. The shape follows the fields
pc/burn_reader.CodexBurnReader and pc/providers/codex_cli read -- `type`,
`timestamp`, `payload.type`, `payload.info.{total,last}_token_usage` and
`payload.rate_limits` -- with the other token fields a real event carries
beside them, set the way the owner's logs measured (2026-11-01, counts
only): total_tokens is input + output, and reasoning is part of output, so a
reader that added reasoning on top would be caught out.

write() is tests/support/transcripts.write, which takes its home from the
caller and checks the path with tests/support/home.inside before it writes.
"""
import os

# write() is the transcripts helper, unchanged: a rollout is a .jsonl of
# compact JSON lines too, and it already takes its home from the caller and
# checks the path with tests/support/home.inside.
from tests.support.transcripts import stamp, write  # noqa: F401


def usage(output, reasoning=None, inp=4000):
    """One token-usage object. Reasoning defaults to a third of output and
    is inside it, as measured."""
    reasoning = output // 3 if reasoning is None else reasoning
    return {"input_tokens": inp, "cached_input_tokens": inp // 2,
            "cache_write_input_tokens": 0, "output_tokens": output,
            "reasoning_output_tokens": reasoning,
            "total_tokens": inp + output}


def weekly_only(pct=21.0, resets_at=1_793_900_000):
    """The owner's Codex Pro shape: a 10080-minute primary, no secondary."""
    return {"limit_id": "codex", "limit_name": None, "plan_type": "pro",
            "credits": None, "individual_limit": None,
            "rate_limit_reached_type": None, "spend_control_reached": None,
            "primary": {"used_percent": pct, "window_minutes": 10080,
                        "resets_at": resets_at},
            "secondary": None}


def with_five_hour(s_pct=40.0, w_pct=21.0, s_reset=1_793_440_000,
                   w_reset=1_793_900_000):
    """The shape before: a 300-minute primary and a 10080 secondary."""
    limits = weekly_only(w_pct, w_reset)
    limits["primary"] = {"used_percent": s_pct, "window_minutes": 300,
                         "resets_at": s_reset}
    limits["secondary"] = {"used_percent": w_pct, "window_minutes": 10080,
                           "resets_at": w_reset}
    return limits


def token_count(at, total_out, last_out=None, limits=None, info=True):
    """One token_count event. `total_out` is the running output total,
    `last_out` this turn's (defaults to the whole total). `limits` None
    leaves rate_limits null; `info` False writes a rate-limit-only event."""
    last_out = total_out if last_out is None else last_out
    payload = {"type": "token_count",
               "info": ({"total_token_usage": usage(total_out, inp=90_000),
                         "last_token_usage": usage(last_out),
                         "model_context_window": 258_400}
                        if info else None),
               "rate_limits": limits}
    return {"timestamp": stamp(at), "type": "event_msg", "payload": payload}


def agent_message(at, text="filler reply text"):
    """A line that is not a token count, with the needle's neighbours."""
    return {"timestamp": stamp(at), "type": "event_msg",
            "payload": {"type": "agent_message", "message": text}}


def rollout_path(sessions, day="2026/11/01", name="rollout-a.jsonl"):
    return os.path.join(str(sessions), *day.split("/"), name)
