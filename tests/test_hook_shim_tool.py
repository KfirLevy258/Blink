"""tools/blink-hook.sh records the CLASS of the tool on PreToolUse ("edit" or
"other"), never its name, and nothing else of the tool.

The sessions card tells "Editing" from "Running a tool" by the tool in
flight, so the shim gained a third sanitiser, built exactly as the project
name's is (docs/sessions-card-design.md, "The tool name"). The full shell
matrix -- dash, busybox, bash -- is tests/ci/check_hook_shim.sh; this is the
same property on whatever `sh` the test machine has, asserted from Python so
the suite catches a regression without the CI scripts.

Every payload here is generated by this file. HOME is the test's own
tmp_path, passed explicitly to the child: the shim writes under $HOME/.blink.
"""
import json
import os
import pathlib
import shutil
import subprocess

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
SHIM = ROOT / "tools" / "blink-hook.sh"

pytestmark = pytest.mark.skipif(shutil.which("sh") is None,
                                reason="needs a POSIX sh")


def _run(home, event, payload, *extra):
    env = {"HOME": str(home), "PATH": os.environ.get("PATH", "")}
    body = payload if isinstance(payload, str) else json.dumps(payload)
    r = subprocess.run(["sh", str(SHIM), event, *extra], input=body.encode(),
                       env=env, capture_output=True, timeout=30)
    assert r.returncode == 0
    assert r.stdout == b"" and r.stderr == b""


def _slot(home, sid, sub="state"):
    p = pathlib.Path(home) / ".blink" / sub / (sid + ".state")
    assert p.exists(), "the shim wrote no slot at all"
    return p.read_text(encoding="utf-8")


def _tool(home, sid, sub="state"):
    return json.loads(_slot(home, sid, sub)).get("tool")


def test_the_tool_is_recorded_on_pretooluse(tmp_path):
    _run(tmp_path, "PreToolUse",
         {"session_id": "s1", "cwd": "/home/x/Proj", "tool_name": "Edit",
          "tool_input": {"file_path": "/home/x/Proj/secret.py"}})
    slot = json.loads(_slot(tmp_path, "s1"))
    assert slot["tool"] == "edit"
    assert slot["event"] == "PreToolUse" and slot["name"] == "Proj"


def test_the_tool_goes_after_every_existing_key(tmp_path):
    # tests/ci/check_hook_shim.sh greps substrings of this line, so the old
    # keys keep their order and the new one is appended.
    _run(tmp_path, "PreToolUse",
         {"session_id": "s1", "cwd": "/home/x/Proj", "tool_name": "Bash"})
    text = _slot(tmp_path, "s1")
    assert text.startswith('{"event":"PreToolUse","t":')
    assert text.endswith(',"name":"Proj","tool":"other"}')


def test_codex_tools_are_recorded_in_their_own_directory(tmp_path):
    _run(tmp_path, "PreToolUse",
         {"session_id": "c1", "tool_name": "apply_patch"}, "codex")
    assert _tool(tmp_path, "c1", "state-codex") == "edit"


@pytest.mark.parametrize("name", ["Edit", "Write", "MultiEdit",
                                  "NotebookEdit", "apply_patch"])
def test_every_editing_tool_is_the_edit_class(tmp_path, name):
    _run(tmp_path, "PreToolUse", {"session_id": "s1", "tool_name": name})
    assert _tool(tmp_path, "s1") == "edit"


@pytest.mark.parametrize("name", ["Bash", "Read", "edit", "Editor",
                                  "mcp__srv__toolname"])
def test_any_other_matched_tool_is_the_other_class(tmp_path, name):
    # "edit" in a payload is a NAME, not the class: only the five above are
    # editing, and the case is the tool's own.
    _run(tmp_path, "PreToolUse", {"session_id": "s1", "tool_name": name})
    assert _tool(tmp_path, "s1") == "other"


@pytest.mark.parametrize("event", ["PostToolUse", "Stop", "UserPromptSubmit",
                                   "PermissionRequest", "Notification"])
def test_no_other_event_records_a_tool(tmp_path, event):
    _run(tmp_path, event, {"session_id": "s1", "tool_name": "Edit"})
    assert _tool(tmp_path, "s1") is None


@pytest.mark.parametrize("payload", [
    # Nested only: the tool's own arguments are never read.
    '{"session_id":"s1","tool_input":{"tool_name":"Edit"}}',
    '{"session_id":"s1","tool_input":{"deep":{"tool_name":"Edit"}}}',
    '{"session_id":"s1","tool_input":[{"tool_name":"Edit"}]}',
    # Characters that would end the JSON string early.
    '{"session_id":"s1","tool_name":"Ed\\"it"}',
    '{"session_id":"s1","tool_name":"Ed\\\\it"}',
    '{"session_id":"s1","tool_name":"has space"}',
    # The bare traversal names and a leading dot.
    '{"session_id":"s1","tool_name":".."}',
    '{"session_id":"s1","tool_name":".hidden"}',
    # Over 24 bytes is refused, never truncated.
    '{"session_id":"s1","tool_name":"%s"}' % ("a" * 25),
    # Not a string.
    '{"session_id":"s1","tool_name":7}',
    # No tool at all is ordinary.
    '{"session_id":"s1"}',
])
def test_a_tool_name_that_does_not_match_is_omitted(tmp_path, payload):
    _run(tmp_path, "PreToolUse", payload)
    text = _slot(tmp_path, "s1")
    assert '"tool"' not in text
    assert "\\" not in text
    json.loads(text)                    # still a slot the daemon can read


def test_the_top_level_tool_wins_over_a_nested_one(tmp_path):
    _run(tmp_path, "PreToolUse",
         '{"session_id":"s1","tool_name":"Read",'
         '"tool_input":{"tool_name":"Edit"}}')
    # Top level Read is "other"; the nested Edit would have made it "edit".
    assert _tool(tmp_path, "s1") == "other"


def test_exactly_24_bytes_is_kept(tmp_path):
    name = "A" + "b" * 23
    _run(tmp_path, "PreToolUse", {"session_id": "s1", "tool_name": name})
    assert _tool(tmp_path, "s1") == "other"     # the class, never the name


def test_a_tool_name_never_appears_anywhere_under_the_state_dir(tmp_path):
    # tests/ci/check_hook_shim.sh case 3, from Python: the payload's "Bash"
    # is read to pick the class and must not be written, in any file.
    _run(tmp_path, "PreToolUse",
         {"session_id": "abc-123", "cwd": "/home/secret/proj",
          "tool_name": "Bash", "hook_event_name": "PreToolUse"})
    files = [p for p in (pathlib.Path(tmp_path) / ".blink").rglob("*")
             if p.is_file()]
    assert files, "the shim wrote nothing"
    for p in files:
        assert "Bash" not in p.name
        assert "Bash" not in p.read_text(encoding="utf-8", errors="replace")
    assert _tool(tmp_path, "abc-123") == "other"


def test_nothing_of_the_tool_input_or_the_full_path_is_written(tmp_path):
    _run(tmp_path, "PreToolUse",
         {"session_id": "s1", "cwd": "/home/secretuser/Proj",
          "tool_name": "Bash",
          "tool_input": {"command": "echo swordfish",
                         "file_path": "/home/secretuser/x"}})
    for p in (pathlib.Path(tmp_path) / ".blink").rglob("*"):
        if p.is_file():
            text = p.read_text(encoding="utf-8", errors="replace")
            assert "swordfish" not in text
            assert "secretuser" not in text
            assert "/home" not in text
